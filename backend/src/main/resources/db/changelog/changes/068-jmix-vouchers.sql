-- ---------------------------------------------------------------- 9. Quyền
WITH res(resource, label, approvable) AS (VALUES
    ('repair_orders', 'phiếu sửa chữa', TRUE),
    ('warranty_claims', 'phiếu bảo hành', FALSE),
    ('maintenance_orders', 'phiếu bảo dưỡng', FALSE),
    ('stock_issues', 'phiếu xuất kho', TRUE),
    ('storage_orders', 'phiếu lưu kho', FALSE),
    ('depreciation_orders', 'bảng tính hao mòn', TRUE),
    ('consumption_records', 'phiếu tiêu hao', FALSE),
    ('room_bookings', 'phiếu đặt phòng', TRUE))
INSERT INTO permissions (code, name, description, system_permission)
SELECT r.resource || ':' || a.action, a.verb || ' ' || r.label, a.description, TRUE
FROM res r
CROSS JOIN (VALUES
    ('read', 'Xem', 'Xem danh sách và chi tiết'),
    ('write', 'Lập', 'Lập, sửa, trình, ghi kết quả'),
    ('delete', 'Xoá', 'Xoá bản ghi nháp'),
    ('export', 'Xuất', 'Xuất dữ liệu ra tệp (PDF, Excel hoặc CSV)'),
    ('approve', 'Duyệt', 'Duyệt, trả lại, từ chối')
) AS a(action, verb, description)
WHERE (a.action <> 'approve' OR r.approvable)
  AND NOT EXISTS (SELECT 1 FROM permissions p WHERE p.code = r.resource || ':' || a.action);

WITH res(resource) AS (VALUES ('repair_orders'), ('warranty_claims'), ('maintenance_orders'), ('stock_issues'),
                              ('storage_orders'), ('depreciation_orders'), ('consumption_records'), ('room_bookings')),
grant_map(role_code, action) AS (VALUES
    ('ADMIN', '%'),
    ('SCHOOL_STAFF', 'read'), ('SCHOOL_STAFF', 'write'), ('SCHOOL_STAFF', 'delete'), ('SCHOOL_STAFF', 'export'),
    ('SCHOOL_LEADER', 'read'), ('SCHOOL_LEADER', 'export'), ('SCHOOL_LEADER', 'approve'),
    ('UBND_LEADER', 'read'), ('UBND_SPECIALIST', 'read'),
    ('SO_LEADER', 'read'), ('SO_LEADER', 'export'), ('SO_SPECIALIST', 'read'), ('SO_SPECIALIST', 'export'))
INSERT INTO role_permissions (role_id, permission_id)
SELECT DISTINCT r.id, p.id
FROM grant_map g CROSS JOIN res
JOIN roles r ON r.code = g.role_code
JOIN permissions p ON p.code LIKE res.resource || ':' || g.action
WHERE NOT EXISTS (SELECT 1 FROM role_permissions rp WHERE rp.role_id = r.id AND rp.permission_id = p.id);

-- Giáo viên đặt phòng bộ môn cho tiết dạy của mình.
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id FROM roles r JOIN permissions p ON p.code IN ('room_bookings:read', 'room_bookings:write', 'room_bookings:delete')
WHERE r.code = 'TEACHER'
  AND NOT EXISTS (SELECT 1 FROM role_permissions rp WHERE rp.role_id = r.id AND rp.permission_id = p.id);

-- ---------------------------------------------------------------- 10. Phạm vi dữ liệu
WITH res(resource) AS (VALUES ('repair_orders'), ('warranty_claims'), ('maintenance_orders'), ('stock_issues'),
                              ('storage_orders'), ('depreciation_orders'), ('consumption_records'), ('room_bookings')),
plan(role_code, action, name, scope) AS (VALUES
    ('ADMIN', 'read', 'Mọi trường', '{"all": []}'),
    ('ADMIN', 'write', 'Mọi trường', '{"all": []}'),
    ('ADMIN', 'delete', 'Mọi trường', '{"all": []}'),
    ('SO_LEADER', 'read', 'Sở xem mọi trường', '{"all": []}'),
    ('SO_SPECIALIST', 'read', 'Sở xem mọi trường', '{"all": []}'),
    ('UBND_LEADER', 'read', 'UBND xem trường trên địa bàn',
     '{"field": "school.id", "op": "in", "value": {"ctx": "user.managedSchoolIds"}}'),
    ('UBND_SPECIALIST', 'read', 'UBND xem trường trên địa bàn',
     '{"field": "school.id", "op": "in", "value": {"ctx": "user.managedSchoolIds"}}'),
    ('SCHOOL_LEADER', 'read', 'Chỉ trường của mình', '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'),
    ('SCHOOL_STAFF', 'read', 'Chỉ trường của mình', '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'),
    ('SCHOOL_STAFF', 'write', 'Chỉ trường của mình', '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'),
    ('SCHOOL_STAFF', 'delete', 'Chỉ trường của mình', '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'))
INSERT INTO row_level_policy (kind, role_id, resource, action, name, description, scope, created_at)
SELECT 'SCOPE', r.id, res.resource, plan.action, plan.name, plan.name, plan.scope::jsonb, now()
FROM plan JOIN roles r ON r.code = plan.role_code CROSS JOIN res
WHERE NOT EXISTS (SELECT 1 FROM row_level_policy p
                  WHERE p.role_id = r.id AND p.resource = res.resource AND p.action = plan.action);

WITH plan(action) AS (VALUES ('read'), ('write'), ('delete'))
INSERT INTO row_level_policy (kind, role_id, resource, action, name, description, scope, created_at)
SELECT 'SCOPE', r.id, 'room_bookings', plan.action, 'Chỉ trường của mình', 'Giáo viên đặt phòng trong trường mình',
       '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'::jsonb, now()
FROM plan JOIN roles r ON r.code = 'TEACHER'
WHERE NOT EXISTS (SELECT 1 FROM row_level_policy p
                  WHERE p.role_id = r.id AND p.resource = 'room_bookings' AND p.action = plan.action);

