-- Lịch sử sửa ô ở vùng chờ nhập dữ liệu: ai sửa, ô nào, từ gì thành gì, và sửa bằng cách nào (tay / sửa nhanh theo
-- luật / AI). Tab "Lịch sử" của lô đọc bảng này; dòng sửa bằng AI, sửa nhanh được tô khác trên lưới.
CREATE TABLE data_import_edits (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id      BIGINT       NOT NULL REFERENCES data_import_batches (id) ON DELETE CASCADE,
    row_id        BIGINT       REFERENCES data_import_rows (id) ON DELETE SET NULL,
    sheet         VARCHAR(20)  NOT NULL,
    row_no        INTEGER      NOT NULL,
    field         VARCHAR(60)  NOT NULL,
    old_value     TEXT,
    new_value     TEXT,
    source        VARCHAR(10)  NOT NULL DEFAULT 'manual',
    edited_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    edited_by_id  BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_data_import_edits_source CHECK (source IN ('manual', 'rule', 'ai'))
);
CREATE INDEX ix_data_import_edits_batch ON data_import_edits (batch_id, edited_at DESC);
COMMENT ON COLUMN data_import_edits.field IS 'Khoá cột của trang; _skip = bỏ / dùng lại dòng';

