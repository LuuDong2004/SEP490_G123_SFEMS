CREATE TABLE legal_documents (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(64)  NOT NULL,
    name            VARCHAR(255) NOT NULL,
    sort_order      INTEGER,
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    note            VARCHAR(500),
    doc_type        VARCHAR(20)  NOT NULL,
    issuer          VARCHAR(255) NOT NULL,
    issued_on       DATE         NOT NULL,
    effective_from  DATE         NOT NULL,
    effective_to    DATE,
    replaces_id     BIGINT       REFERENCES legal_documents (id) ON DELETE RESTRICT,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ,
    created_by_id   BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id   BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_legal_documents_type CHECK (doc_type IN ('LUAT', 'NGHI_DINH', 'THONG_TU', 'QUYET_DINH', 'CONG_VAN', 'HUONG_DAN', 'KHAC')),
    CONSTRAINT ck_legal_documents_dates CHECK (effective_from >= issued_on AND (effective_to IS NULL OR effective_to > effective_from)),
    CONSTRAINT ck_legal_documents_self CHECK (replaces_id IS NULL OR replaces_id <> id)
);
CREATE UNIQUE INDEX ux_legal_documents_code ON legal_documents (code);
CREATE INDEX ix_legal_documents_replaces ON legal_documents (replaces_id);

