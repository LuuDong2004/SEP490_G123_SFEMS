INSERT INTO role_permissions (role_id, permission_id)
SELECT rp.role_id, np.id
FROM role_permissions rp
JOIN permissions op ON op.id = rp.permission_id
JOIN permissions np ON (op.code = 'movement_reasons:read' AND np.code = 'legal_documents:read')
                    OR (op.code = 'movement_reasons:write' AND np.code IN ('legal_documents:write', 'legal_documents:delete'))
WHERE NOT EXISTS (SELECT 1 FROM role_permissions x WHERE x.role_id = rp.role_id AND x.permission_id = np.id);
