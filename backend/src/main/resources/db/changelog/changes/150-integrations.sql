-- Quản lý kết nối và giao dịch với hệ thống ngoài (QLTB-253, 225 — UC28; khung cho QLTB-251, 449, 144). Chưa có
-- đối tác cụ thể (CSDL ngành của Bộ, SSO của Sở…): đây là KHUNG — khai báo hệ thống, kiểm tra kết nối, nhật ký mọi
-- lần trao đổi và chạy lại lần lỗi. Bộ nối của từng đối tác cắm vào sau, ghi cùng nhật ký này.
CREATE TABLE integration_systems (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(40)   NOT NULL,
    name             VARCHAR(200)  NOT NULL,
    kind             VARCHAR(30)   NOT NULL,
    base_url         VARCHAR(500)  NOT NULL,
    health_path      VARCHAR(300),
    auth_type        VARCHAR(20)   NOT NULL DEFAULT 'NONE',
    credential       VARCHAR(2000),
    active           BOOLEAN       NOT NULL DEFAULT TRUE,
    note             VARCHAR(1000),
    last_checked_at  TIMESTAMP WITH TIME ZONE,
    last_status      VARCHAR(20)   NOT NULL DEFAULT 'UNKNOWN',
    last_latency_ms  INTEGER,
    last_error       VARCHAR(1000),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at       TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_integration_systems_code UNIQUE (code),
    CONSTRAINT ck_integration_systems_kind CHECK (kind IN ('CSDL_NGANH', 'SSO', 'DONG_BO', 'KHAC')),
    CONSTRAINT ck_integration_systems_auth CHECK (auth_type IN ('NONE', 'BEARER', 'API_KEY', 'BASIC')),
    CONSTRAINT ck_integration_systems_status CHECK (last_status IN ('UNKNOWN', 'UP', 'DOWN'))
);
COMMENT ON COLUMN integration_systems.credential IS 'Token / khoá / mật khẩu đã mã hoá (SecretBox, AES-GCM) — không bao giờ trả ra API';

CREATE TABLE integration_transactions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    system_id         BIGINT        NOT NULL REFERENCES integration_systems (id) ON DELETE CASCADE,
    direction         VARCHAR(10)   NOT NULL,
    operation         VARCHAR(80)   NOT NULL,
    status            VARCHAR(20)   NOT NULL,
    http_status       INTEGER,
    latency_ms        INTEGER,
    request_summary   VARCHAR(1000),
    response_summary  VARCHAR(2000),
    error             VARCHAR(1000),
    attempt           INTEGER       NOT NULL DEFAULT 1,
    retry_of_id       BIGINT REFERENCES integration_transactions (id) ON DELETE SET NULL,
    actor_id          BIGINT,
    actor_name        VARCHAR(150),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT ck_integration_tx_direction CHECK (direction IN ('OUT', 'IN')),
    CONSTRAINT ck_integration_tx_status CHECK (status IN ('SUCCESS', 'FAILED'))
);
CREATE INDEX ix_integration_tx_system ON integration_transactions (system_id, created_at);
CREATE INDEX ix_integration_tx_status ON integration_transactions (status, created_at);

