-- ---------------------------------------------------------------- 1. Báo hỏng - sửa chữa
--
-- Một phiếu cho cả vòng: ghi nhận hỏng → chọn cách xử lý → (duyệt chi phí nếu
-- thuê sửa) → ghi kết quả. Tách "báo hỏng" và "sửa chữa" thành hai phiếu thì
-- cán bộ phải lập hai lần cho cùng một cái máy, và cái nối hai phiếu lại chỉ là
-- một ô ghi chú.
CREATE TABLE damage_reports (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id         BIGINT       NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    code              VARCHAR(32),
    report_date       DATE         NOT NULL,
    reporter_id       BIGINT REFERENCES staff (id) ON DELETE RESTRICT,
    description       VARCHAR(1000),
    severity          VARCHAR(20),
    handling          VARCHAR(20)  NOT NULL DEFAULT 'SELF_REPAIR',
    vendor            VARCHAR(255),
    estimated_cost    NUMERIC(18, 2),
    actual_cost       NUMERIC(18, 2),
    result            VARCHAR(20),
    result_note       VARCHAR(1000),
    result_date       DATE,
    source_resource   VARCHAR(60),
    source_id         BIGINT,
    source_code       VARCHAR(40),
    status            VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    approval_step     VARCHAR(20),
    submitted_at      TIMESTAMP WITH TIME ZONE,
    submitted_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    completed_at      TIMESTAMP WITH TIME ZONE,
    completed_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    cancel_reason     VARCHAR(500),
    reject_reason     VARCHAR(500),
    return_note       VARCHAR(500),
    note              VARCHAR(500),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE,
    created_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_damage_reports_school_code UNIQUE (school_id, code),
    CONSTRAINT ck_damage_reports_costs CHECK (
        (estimated_cost IS NULL OR estimated_cost >= 0) AND (actual_cost IS NULL OR actual_cost >= 0))
);
CREATE INDEX ix_damage_reports_school ON damage_reports (school_id, status);

CREATE TABLE damage_report_lines (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id       BIGINT  NOT NULL REFERENCES damage_reports (id) ON DELETE CASCADE,
    line_no         INTEGER NOT NULL,
    equipment_id    BIGINT  NOT NULL REFERENCES equipment (id) ON DELETE RESTRICT,
    note            VARCHAR(255)
);
CREATE INDEX ix_damage_report_lines_equipment ON damage_report_lines (equipment_id);

-- ---------------------------------------------------------------- 2. Kế hoạch bảo trì định kỳ
--
-- Một kế hoạch là "cái gì, bao lâu một lần, lần tới là khi nào, ai lo". Mỗi lần
-- bảo trì xong thì ngày lần tới tự lùi thêm một chu kỳ, và hệ thống nhắc trước
-- 7 ngày.
CREATE TABLE maintenance_plans (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id         BIGINT       NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    code              VARCHAR(64)  NOT NULL,
    name              VARCHAR(255) NOT NULL,
    sort_order        INTEGER,
    active            BOOLEAN      NOT NULL DEFAULT TRUE,
    note              VARCHAR(500),
    equipment_id      BIGINT REFERENCES equipment (id) ON DELETE CASCADE,
    room_id           BIGINT REFERENCES rooms (id) ON DELETE CASCADE,
    frequency         VARCHAR(20)  NOT NULL DEFAULT 'SEMI_ANNUAL',
    next_due_date     DATE         NOT NULL,
    last_done_date    DATE,
    responsible_id    BIGINT REFERENCES staff (id) ON DELETE SET NULL,
    notified_at       TIMESTAMP WITH TIME ZONE,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE,
    created_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_maintenance_plans_school_code UNIQUE (school_id, code)
);
CREATE INDEX ix_maintenance_plans_due ON maintenance_plans (active, next_due_date);

-- ---------------------------------------------------------------- 3. Quyền
INSERT INTO permissions (code, name, description, system_permission)
SELECT r.resource || ':' || a.action, a.verb || ' ' || r.label, a.description, TRUE
FROM (VALUES ('damage_reports', 'phiếu báo hỏng - sửa chữa'), ('maintenance_plans', 'kế hoạch bảo trì')) AS r(resource, label)
CROSS JOIN (VALUES
    ('read',    'Xem',   'Xem danh sách và chi tiết'),
    ('write',   'Lập',   'Lập, sửa, trình, ghi kết quả'),
    ('delete',  'Xoá',   'Xoá bản ghi nháp'),
    ('export',  'Xuất',  'Xuất dữ liệu ra tệp (PDF, Excel hoặc CSV)'),
    ('approve', 'Duyệt', 'Duyệt chi phí sửa chữa, trả lại, từ chối')
) AS a(action, verb, description)
WHERE NOT (r.resource = 'maintenance_plans' AND a.action = 'approve')
  AND NOT EXISTS (SELECT 1 FROM permissions p WHERE p.code = r.resource || ':' || a.action);

WITH grant_map(role_code, pattern) AS (VALUES
    ('ADMIN', 'damage_reports:%'), ('ADMIN', 'maintenance_plans:%'),
    ('SCHOOL_STAFF', 'damage_reports:read'), ('SCHOOL_STAFF', 'damage_reports:write'),
    ('SCHOOL_STAFF', 'damage_reports:delete'), ('SCHOOL_STAFF', 'damage_reports:export'),
    ('SCHOOL_STAFF', 'maintenance_plans:read'), ('SCHOOL_STAFF', 'maintenance_plans:write'),
    ('SCHOOL_STAFF', 'maintenance_plans:delete'), ('SCHOOL_STAFF', 'maintenance_plans:export'),
    ('SCHOOL_LEADER', 'damage_reports:read'), ('SCHOOL_LEADER', 'damage_reports:export'),
    ('SCHOOL_LEADER', 'damage_reports:approve'), ('SCHOOL_LEADER', 'maintenance_plans:read'),
    ('UBND_LEADER', 'damage_reports:read'), ('UBND_LEADER', 'maintenance_plans:read'),
    ('UBND_SPECIALIST', 'damage_reports:read'), ('UBND_SPECIALIST', 'maintenance_plans:read'),
    ('SO_LEADER', 'damage_reports:read'), ('SO_LEADER', 'damage_reports:export'), ('SO_LEADER', 'maintenance_plans:read'),
    ('SO_SPECIALIST', 'damage_reports:read'), ('SO_SPECIALIST', 'damage_reports:export'),
    ('SO_SPECIALIST', 'maintenance_plans:read')
)
INSERT INTO role_permissions (role_id, permission_id)
SELECT DISTINCT r.id, p.id
FROM grant_map g JOIN roles r ON r.code = g.role_code JOIN permissions p ON p.code LIKE g.pattern
WHERE NOT EXISTS (SELECT 1 FROM role_permissions rp WHERE rp.role_id = r.id AND rp.permission_id = p.id);

-- ---------------------------------------------------------------- 4. Phạm vi dữ liệu
WITH res(resource) AS (VALUES ('damage_reports'), ('maintenance_plans')),
plan(role_code, action, name, scope) AS (VALUES
    ('ADMIN', 'read', 'Mọi trường', '{"all": []}'),
    ('ADMIN', 'write', 'Mọi trường', '{"all": []}'),
    ('ADMIN', 'delete', 'Mọi trường', '{"all": []}'),
    ('SO_LEADER', 'read', 'Sở xem mọi trường', '{"all": []}'),
    ('SO_SPECIALIST', 'read', 'Sở xem mọi trường', '{"all": []}'),
    ('UBND_LEADER', 'read', 'UBND xem trường trên địa bàn',
     '{"field": "school.id", "op": "in", "value": {"ctx": "user.managedSchoolIds"}}'),
    ('UBND_SPECIALIST', 'read', 'UBND xem trường trên địa bàn',
     '{"field": "school.id", "op": "in", "value": {"ctx": "user.managedSchoolIds"}}'),
    ('SCHOOL_LEADER', 'read', 'Chỉ trường của mình', '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'),
    ('SCHOOL_STAFF', 'read', 'Chỉ trường của mình', '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'),
    ('SCHOOL_STAFF', 'write', 'Chỉ trường của mình', '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'),
    ('SCHOOL_STAFF', 'delete', 'Chỉ trường của mình', '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'))
INSERT INTO row_level_policy (kind, role_id, resource, action, name, description, scope, created_at)
SELECT 'SCOPE', r.id, res.resource, plan.action, plan.name, plan.name, plan.scope::jsonb, now()
FROM plan JOIN roles r ON r.code = plan.role_code CROSS JOIN res
WHERE NOT EXISTS (SELECT 1 FROM row_level_policy p
                  WHERE p.role_id = r.id AND p.resource = res.resource AND p.action = plan.action);
