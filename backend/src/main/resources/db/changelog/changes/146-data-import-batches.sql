-- Đổ dữ liệu đầu vào qua VÙNG CHỜ.
--
-- Tệp đầu vào của một trường (cơ sở, cán bộ, khối nhà, phòng, lớp, thiết bị — một tệp nhiều trang) không ghi
-- thẳng vào sổ: nó được đọc vào một LÔ NHẬP, mỗi dòng của tệp một dòng `data_import_rows` giữ nguyên chữ người
-- dùng gõ. Người nhập xem lỗi, sửa từng ô, bỏ dòng ngay trên hệ thống rồi mới bấm ghi; ghi xong vẫn hoàn tác
-- được cả lô khi chưa có nghiệp vụ nào dùng tới dữ liệu đó. Dữ liệu đã ghi nằm ở `data_import_records`.
--
-- `equipment_catalog_aliases` là bảng đối chiếu mã thiết bị của phần mềm cũ (MISA…) sang danh mục: mỗi lần
-- ghi, dòng nào mang mã lạ mà đã ghép được vào danh mục (theo tên, công thức, hoặc người nhập chọn) thì mã đó
-- được nhớ lại — trường sau dùng cùng phần mềm cũ thì ghép ngay theo mã.

--changeset qltb:146-data-import-batches

CREATE TABLE data_import_batches (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id         BIGINT       NOT NULL REFERENCES schools (id) ON DELETE CASCADE,
    file_name         VARCHAR(255) NOT NULL,
    status            VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    note              VARCHAR(500),
    committed_at      TIMESTAMP WITH TIME ZONE,
    committed_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    history_count     INTEGER,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at        TIMESTAMP WITH TIME ZONE,
    created_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_data_import_batches_status CHECK (status IN ('DRAFT', 'COMMITTED'))
);
CREATE INDEX ix_data_import_batches_school ON data_import_batches (school_id);

COMMENT ON TABLE data_import_batches IS 'Lô nhập dữ liệu đầu vào của một trường: tệp đã đọc vào vùng chờ, sửa được trước khi ghi';
COMMENT ON COLUMN data_import_batches.history_count IS 'Số dòng lịch sử của các tài sản lô đã tạo, lúc ghi — tăng lên nghĩa là đã có nghiệp vụ, không hoàn tác được';

CREATE TABLE data_import_rows (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id  BIGINT      NOT NULL REFERENCES data_import_batches (id) ON DELETE CASCADE,
    sheet     VARCHAR(20) NOT NULL,
    row_no    INTEGER     NOT NULL,
    data      JSONB       NOT NULL DEFAULT '{}'::jsonb,
    skipped   BOOLEAN     NOT NULL DEFAULT FALSE,
    status    VARCHAR(20) NOT NULL DEFAULT 'OK',
    messages  JSONB       NOT NULL DEFAULT '[]'::jsonb,
    resolved  JSONB       NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX ix_data_import_rows_batch ON data_import_rows (batch_id, sheet, row_no);

COMMENT ON COLUMN data_import_rows.row_no IS 'Dòng trong tệp gốc (dòng thêm trên hệ thống: số kế tiếp)';
COMMENT ON COLUMN data_import_rows.status IS 'OK, WARNING, ERROR, EXISTS (đã có trên hệ thống — không tạo lại), SKIPPED';
COMMENT ON COLUMN data_import_rows.messages IS 'Lỗi / cảnh báo của lần kiểm tra gần nhất: [{level, field, text}]';
COMMENT ON COLUMN data_import_rows.resolved IS 'Thứ hệ thống hiểu được từ dòng, vd thiết bị trong danh mục đã ghép';

CREATE TABLE data_import_records (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id   BIGINT      NOT NULL REFERENCES data_import_batches (id) ON DELETE CASCADE,
    resource   VARCHAR(40) NOT NULL,
    record_id  BIGINT      NOT NULL
);
CREATE INDEX ix_data_import_records_batch ON data_import_records (batch_id, resource);

CREATE TABLE equipment_catalog_aliases (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alias       VARCHAR(64) NOT NULL,
    catalog_id  BIGINT      NOT NULL REFERENCES equipment_catalogs (id) ON DELETE CASCADE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_equipment_catalog_aliases_alias ON equipment_catalog_aliases (UPPER(alias));

COMMENT ON TABLE equipment_catalog_aliases IS 'Mã thiết bị của phần mềm cũ (MISA…) → thiết bị trong danh mục, học dần từ các lần nhập dữ liệu đầu vào';

