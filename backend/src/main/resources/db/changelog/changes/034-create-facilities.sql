CREATE TABLE campuses (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id      BIGINT NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    code           VARCHAR(64)  NOT NULL,
    name           VARCHAR(255) NOT NULL,
    sort_order     INTEGER,
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    note           VARCHAR(500),
    is_primary     BOOLEAN      NOT NULL DEFAULT FALSE,
    phone          VARCHAR(30),
    address        VARCHAR(500),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE,
    created_by_id  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_campuses_school_code UNIQUE (school_id, code)
);
-- Mỗi trường tối đa một cơ sở chính — database giữ, service tự bỏ cờ cơ sở cũ.
CREATE UNIQUE INDEX uq_campuses_primary ON campuses (school_id) WHERE is_primary;

CREATE TABLE buildings (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id          BIGINT NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    code               VARCHAR(64)  NOT NULL,
    name               VARCHAR(255) NOT NULL,
    sort_order         INTEGER,
    active             BOOLEAN      NOT NULL DEFAULT TRUE,
    note               VARCHAR(500),
    campus_id          BIGINT REFERENCES campuses (id) ON DELETE RESTRICT,
    floor_count        INTEGER,
    built_year         INTEGER,
    floor_area         NUMERIC(12, 2),
    condition          VARCHAR(30),
    managing_staff_id  BIGINT REFERENCES staff (id) ON DELETE SET NULL,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE,
    created_by_id      BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id      BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_buildings_school_code UNIQUE (school_id, code),
    CONSTRAINT ck_buildings_floor_count CHECK (floor_count IS NULL OR floor_count >= 0),
    CONSTRAINT ck_buildings_floor_area CHECK (floor_area IS NULL OR floor_area >= 0)
);
CREATE INDEX ix_buildings_school ON buildings (school_id);

CREATE TABLE rooms (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id          BIGINT NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    code               VARCHAR(64)  NOT NULL,
    name               VARCHAR(255) NOT NULL,
    sort_order         INTEGER,
    active             BOOLEAN      NOT NULL DEFAULT TRUE,
    note               VARCHAR(500),
    campus_id          BIGINT REFERENCES campuses (id) ON DELETE RESTRICT,
    building_id        BIGINT REFERENCES buildings (id) ON DELETE RESTRICT,
    room_type_id       BIGINT REFERENCES room_types (id) ON DELETE RESTRICT,
    location           VARCHAR(255),
    floor              VARCHAR(50),
    area               NUMERIC(10, 2),
    capacity           INTEGER,
    condition          VARCHAR(30),
    usage_status       VARCHAR(30),
    managing_staff_id  BIGINT REFERENCES staff (id) ON DELETE SET NULL,
    managing_unit      VARCHAR(255),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE,
    created_by_id      BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id      BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_rooms_school_code UNIQUE (school_id, code),
    CONSTRAINT ck_rooms_area CHECK (area IS NULL OR area >= 0),
    CONSTRAINT ck_rooms_capacity CHECK (capacity IS NULL OR capacity >= 0)
);
CREATE INDEX ix_rooms_school ON rooms (school_id);
CREATE INDEX ix_rooms_building ON rooms (building_id);

