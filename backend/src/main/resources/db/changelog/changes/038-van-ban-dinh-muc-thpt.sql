ALTER TABLE equipment_standards
    ADD COLUMN previous_standard_id BIGINT REFERENCES equipment_standards (id) ON DELETE SET NULL;
ALTER TABLE equipment_standards
    ADD CONSTRAINT ck_equipment_standards_not_self
    CHECK (previous_standard_id IS NULL OR previous_standard_id <> id);
CREATE UNIQUE INDEX uq_equipment_standards_one_draft_per_source
    ON equipment_standards (previous_standard_id)
    WHERE status = 'DRAFT' AND previous_standard_id IS NOT NULL;

CREATE TABLE equipment_standard_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    standard_id BIGINT NOT NULL REFERENCES equipment_standards (id) ON DELETE CASCADE,
    document_role VARCHAR(20) NOT NULL DEFAULT 'MAIN',
    document_no VARCHAR(100) NOT NULL,
    document_name VARCHAR(500),
    issuing_authority VARCHAR(255),
    issue_date DATE,
    effective_date DATE,
    url VARCHAR(1000),
    sort_order INTEGER,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE,
    created_by_id BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_standard_document_no UNIQUE (standard_id, document_no)
);
CREATE INDEX ix_standard_documents_standard ON equipment_standard_documents (standard_id);

ALTER TABLE equipment_norms ADD COLUMN source_document_id BIGINT
    REFERENCES equipment_standard_documents (id) ON DELETE SET NULL;
CREATE INDEX ix_equipment_norms_source_document ON equipment_norms (source_document_id);

INSERT INTO equipment_standard_documents
    (standard_id, document_role, document_no, document_name, issuing_authority,
     issue_date, effective_date, sort_order, created_at)
SELECT s.id, v.role, v.no, v.name, 'Bộ Giáo dục và Đào tạo', v.issued::date, v.effective::date, v.ord, now()
FROM (VALUES
    ('STD-THPT-06-VBHN', 'MAIN', '39/2021/TT-BGDĐT',
     'Ban hành Danh mục thiết bị dạy học tối thiểu cấp Trung học phổ thông', '2021-12-30', '2022-02-14', 1),
    ('STD-THPT-06-VBHN', 'AMENDMENT', '26/2023/TT-BGDĐT',
     'Sửa đổi, bổ sung Danh mục thiết bị dạy học tối thiểu', '2023-12-28', '2024-02-12', 2),
    ('TT39-2021-THPT', 'MAIN', '39/2021/TT-BGDĐT',
     'Ban hành Danh mục thiết bị dạy học tối thiểu cấp Trung học phổ thông', '2021-12-30', '2022-02-14', 1)
) AS v(std, role, no, name, issued, effective, ord)
JOIN equipment_standards s ON s.code = v.std
ON CONFLICT (standard_id, document_no) DO NOTHING;

UPDATE equipment_norms n SET source_document_id = d.id
FROM equipment_standards s JOIN equipment_standard_documents d
    ON d.standard_id = s.id AND d.document_role = 'MAIN'
WHERE n.standard_id = s.id AND n.source_document_id IS NULL;
