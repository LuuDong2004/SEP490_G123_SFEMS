--comment Hồ sơ năm học theo điểm trường (Đang khai → Đã xác nhận) và bản chốt năm học dạng dòng (docs/du-lieu-theo-nam-hoc.md §2.C, §3).
-- school_year_profiles: trạng thái từng điểm trường; không có dòng = "Đang khai". campus_id trống = trường chưa khai cơ sở.
CREATE TABLE school_year_profiles (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id       BIGINT NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    school_year_id  BIGINT NOT NULL REFERENCES school_years (id) ON DELETE RESTRICT,
    campus_id       BIGINT REFERENCES campuses (id) ON DELETE CASCADE,
    status          VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    confirmed_at    TIMESTAMP WITH TIME ZONE,
    confirmed_by_id BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT ck_school_year_profiles_status CHECK (status IN ('DRAFT', 'CONFIRMED'))
);
CREATE UNIQUE INDEX uq_school_year_profiles ON school_year_profiles (school_id, school_year_id, COALESCE(campus_id, 0));

-- Mỗi lần chốt một dòng; mở lại thì dòng thành REOPENED (giữ làm lịch sử), chốt lại là dòng mới. campus_id trống = cả trường.
CREATE TABLE school_year_closings (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id      BIGINT NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    school_year_id BIGINT NOT NULL REFERENCES school_years (id) ON DELETE RESTRICT,
    campus_id      BIGINT REFERENCES campuses (id) ON DELETE SET NULL,
    status         VARCHAR(20) NOT NULL DEFAULT 'CLOSED',
    closed_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    closed_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    reopened_at    TIMESTAMP WITH TIME ZONE,
    reopened_by_id BIGINT REFERENCES users (id) ON DELETE SET NULL,
    reopen_reason  VARCHAR(1000),
    CONSTRAINT ck_school_year_closings_status CHECK (status IN ('CLOSED', 'REOPENED')),
    CONSTRAINT ck_school_year_closings_reason CHECK (status = 'CLOSED' OR reopen_reason IS NOT NULL)
);
CREATE UNIQUE INDEX uq_school_year_closings_active ON school_year_closings (school_id, school_year_id) WHERE status = 'CLOSED';
CREATE INDEX ix_school_year_closings_school ON school_year_closings (school_id, school_year_id);

-- Ảnh chụp kết quả chuẩn tối thiểu: một dòng mỗi thiết bị mỗi điểm trường (tổng trường = cộng các điểm).
CREATE TABLE school_year_closing_lines (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    closing_id        BIGINT NOT NULL REFERENCES school_year_closings (id) ON DELETE CASCADE,
    campus_id         BIGINT REFERENCES campuses (id) ON DELETE SET NULL,
    campus_name       VARCHAR(255),
    norm_id           BIGINT REFERENCES equipment_norms (id) ON DELETE SET NULL,
    norm_code         VARCHAR(64),
    catalog_id        BIGINT REFERENCES equipment_catalogs (id) ON DELETE SET NULL,
    catalog_code      VARCHAR(64),
    name              VARCHAR(255) NOT NULL,
    subject_name      VARCHAR(255),
    unit_name         VARCHAR(100),
    allowed_kind      VARCHAR(20),
    basis_text        VARCHAR(1000),
    required_tt       INTEGER,
    required_adjusted INTEGER,
    current_qty       INTEGER NOT NULL DEFAULT 0,
    broken            INTEGER NOT NULL DEFAULT 0,
    lost              INTEGER NOT NULL DEFAULT 0,
    pending_disposal  INTEGER NOT NULL DEFAULT 0,
    shortage_tt       INTEGER,
    shortage_adjusted INTEGER,
    surplus           INTEGER,
    outside_need      INTEGER,
    proposed          INTEGER NOT NULL DEFAULT 0,
    adjust_kind       VARCHAR(20),
    adjust_status     VARCHAR(20),
    adjust_reason     VARCHAR(1000),
    warning           VARCHAR(255)
);
CREATE INDEX ix_school_year_closing_lines_closing ON school_year_closing_lines (closing_id);

-- Số đầu vào lúc chốt: lớp, sĩ số theo khối; giáo viên, phòng bộ môn theo môn — từng điểm trường.
CREATE TABLE school_year_closing_inputs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    closing_id BIGINT NOT NULL REFERENCES school_year_closings (id) ON DELETE CASCADE,
    campus_id  BIGINT REFERENCES campuses (id) ON DELETE SET NULL,
    kind       VARCHAR(20) NOT NULL,
    ref_id     BIGINT,
    ref_name   VARCHAR(255),
    classes    INTEGER,
    students   INTEGER,
    teachers   INTEGER,
    rooms      INTEGER,
    CONSTRAINT ck_school_year_closing_inputs_kind CHECK (kind IN ('GRADE', 'SUBJECT'))
);
CREATE INDEX ix_school_year_closing_inputs_closing ON school_year_closing_inputs (closing_id);

