ALTER TABLE equipment_transfers ADD COLUMN delivery_phase VARCHAR(30);
ALTER TABLE equipment_transfers ADD COLUMN provisional_reported_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE equipment_transfer_lines ADD COLUMN reported_result VARCHAR(20);
ALTER TABLE equipment_transfer_lines ADD COLUMN reported_condition VARCHAR(20);
ALTER TABLE equipment_transfer_lines ADD COLUMN reported_note VARCHAR(500);
ALTER TABLE equipment_transfer_lines ADD COLUMN replacement_for_line_id BIGINT REFERENCES equipment_transfer_lines(id);

CREATE TABLE equipment_transfer_supplements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id BIGINT NOT NULL REFERENCES equipment_transfers(id) ON DELETE CASCADE,
    attempt_no INTEGER NOT NULL,
    dispatch_date DATE NOT NULL,
    sender_name VARCHAR(255),
    note VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_transfer_supplement_attempt UNIQUE (transfer_id, attempt_no)
);
CREATE INDEX ix_transfer_supplements_transfer ON equipment_transfer_supplements(transfer_id);

CREATE TABLE equipment_transfer_supplement_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplement_id BIGINT NOT NULL REFERENCES equipment_transfer_supplements(id) ON DELETE CASCADE,
    original_line_id BIGINT NOT NULL REFERENCES equipment_transfer_lines(id),
    delivered_line_id BIGINT NOT NULL REFERENCES equipment_transfer_lines(id),
    CONSTRAINT uq_transfer_supplement_item UNIQUE (supplement_id, delivered_line_id)
);

-- Dòng của phiếu chưa hoàn tất từng dùng chung cột receipt_result cho báo tạm.
-- Chuyển nó sang cột riêng để chưa có quyết định nhận/trả cuối cùng.
UPDATE equipment_transfer_lines l SET reported_result = l.receipt_result,
    reported_condition = l.received_condition, reported_note = l.receive_note,
    receipt_result = NULL, received_condition = NULL, receive_note = NULL
FROM equipment_transfers t WHERE t.id = l.transfer_id AND t.status = 'APPROVED'
  AND l.receipt_result IS NOT NULL;
UPDATE equipment_transfers SET delivery_phase = 'WAITING_SUPPLEMENT',
    provisional_reported_at = COALESCE(updated_at, CURRENT_TIMESTAMP)
WHERE status = 'APPROVED' AND id IN (
    SELECT DISTINCT transfer_id FROM equipment_transfer_lines WHERE reported_result IS NOT NULL
);
UPDATE equipment_transfers SET delivery_phase = 'IN_TRANSIT'
WHERE status = 'APPROVED' AND delivery_phase IS NULL;
UPDATE equipment_transfers SET delivery_phase = 'COMPLETED'
WHERE status = 'COMPLETED' AND delivery_phase IS NULL;
