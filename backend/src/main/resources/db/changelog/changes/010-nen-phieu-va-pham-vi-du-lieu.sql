--comment Nền chung của mọi loại phiếu (đề xuất mua sắm, phiếu nhập, phiếu kiểm kê): nhật ký duyệt, dãy số phiếu, luồng phê duyệt cấu hình được; và phạm vi dữ liệu theo trường cho 5 vai trò trên các bảng thuộc trường.

-- ---------------------------------------------------------------- 1. Nhật ký duyệt
--
-- Mỗi lần một phiếu đổi trạng thái — trình, duyệt, trả lại, từ chối, huỷ, hoàn tất — là MỘT dòng ở
-- đây. Một bảng cho MỌI loại phiếu, khoá bằng (resource, voucher_id) chứ không phải khoá ngoại: ba loại
-- phiếu với ba bảng nhật ký gần giống hệt nhau là ba chỗ để quên một cột. Phiếu đã có dòng nhật ký thì
-- không xoá được (VoucherWorkflow.requireDeletable), nên không có dòng nào mồ côi.
CREATE TABLE voucher_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource     VARCHAR(60)  NOT NULL,
    voucher_id   BIGINT       NOT NULL,
    action       VARCHAR(20)  NOT NULL,
    from_status  VARCHAR(20),
    to_status    VARCHAR(20)  NOT NULL,
    step         VARCHAR(20),
    note         VARCHAR(500),
    actor_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    actor_name   VARCHAR(150),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_voucher_events_voucher ON voucher_events (resource, voucher_id, created_at);

-- ---------------------------------------------------------------- 2. Dãy số phiếu
--
-- Số phiếu <tiền tố>-<năm>-<5 chữ số>, đếm riêng cho từng trường và từng dãy (DocumentNumberService).
-- Cột prefix giữ cả năm ("NK-2026") nên mỗi năm là một dòng đếm mới.
CREATE TABLE document_number_sequences (
    school_id      BIGINT      NOT NULL REFERENCES schools (id) ON DELETE CASCADE,
    prefix         VARCHAR(20) NOT NULL,
    current_number INTEGER     NOT NULL DEFAULT 0,
    PRIMARY KEY (school_id, prefix)
);

-- ---------------------------------------------------------------- 3. Luồng phê duyệt cấu hình được
--
-- Mỗi loại phiếu có thể có MỘT dòng: các bước (theo thứ tự cấp SCHOOL → MANAGING_BODY) và tuỳ chọn một
-- ngưỡng tiền — phiếu từ ngưỡng trở lên đi theo các bước khác. Loại phiếu không có dòng chạy luồng mặc
-- định trong code (ApprovalFlowType), nên changelog này không seed dòng nào.
CREATE TABLE approval_flows (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource         VARCHAR(60)  NOT NULL,
    steps            VARCHAR(100) NOT NULL DEFAULT '',
    amount_threshold NUMERIC(18, 2),
    steps_above      VARCHAR(100),
    note             VARCHAR(500),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE,
    created_by_id    BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id    BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_approval_flows_resource UNIQUE (resource),
    CONSTRAINT ck_approval_flows_threshold CHECK (amount_threshold IS NULL OR amount_threshold > 0),
    CONSTRAINT ck_approval_flows_above CHECK ((amount_threshold IS NULL) = (steps_above IS NULL))
);
COMMENT ON TABLE approval_flows IS 'Luồng phê duyệt cấu hình cho từng loại phiếu; không có dòng = luồng mặc định trong code';
COMMENT ON COLUMN approval_flows.steps IS 'Các bước, mã ngăn bằng dấu phẩy, theo thứ tự cấp: SCHOOL,MANAGING_BODY; rỗng = trình là xong';

-- Chỉ quản trị viên sửa luồng duyệt: đổi luồng là đổi AI KÝ phiếu nào, quyết định của lãnh đạo, quản trị
-- viên nhập vào. Mọi tài khoản đăng nhập đều đọc được các bước của một loại phiếu (endpoint /steps không
-- cần mã quyền) để form biết nút là "Trình" hay "Duyệt".
INSERT INTO permissions (code, name, description, system_permission) VALUES
  ('approval_flows:read',  'Xem luồng phê duyệt', 'Xem các bước duyệt của từng loại phiếu',                   TRUE),
  ('approval_flows:write', 'Sửa luồng phê duyệt', 'Đổi các bước duyệt và ngưỡng tiền của từng loại phiếu',    TRUE);

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r JOIN permissions p ON p.code IN ('approval_flows:read', 'approval_flows:write')
WHERE r.code = 'ADMIN'
  AND NOT EXISTS (SELECT 1 FROM role_permissions rp WHERE rp.role_id = r.id AND rp.permission_id = p.id);

-- ---------------------------------------------------------------- 4. Cột chung của bảng phiếu (ghi chú)
--
-- Bảng của một loại phiếu kế thừa SchoolVoucher phải có đủ các cột sau, ngoài cột riêng của nó:
--
--   id, created_at, updated_at, created_by_id, updated_by_id   (BaseEntity)
--   school_id        BIGINT NOT NULL REFERENCES schools (id)
--   code             VARCHAR(32)            -- số phiếu, NULL tới khi trình; UNIQUE (school_id, code)
--   status           VARCHAR(20) NOT NULL   -- DRAFT|PENDING|APPROVED|COMPLETED|REJECTED|CANCELLED
--   approval_step    VARCHAR(20)            -- SCHOOL|MANAGING_BODY, chỉ khi PENDING
--   reached_step     VARCHAR(20)
--   submitted_at     TIMESTAMP WITH TIME ZONE
--   submitted_by_id  BIGINT REFERENCES users (id) ON DELETE SET NULL
--   completed_at     TIMESTAMP WITH TIME ZONE
--   completed_by_id  BIGINT REFERENCES users (id) ON DELETE SET NULL
--   cancel_reason    VARCHAR(500)
--   reject_reason    VARCHAR(500)
--   return_note      VARCHAR(500)
--   note             VARCHAR(500)
--
-- Người phụ trách loại phiếu tạo bảng trong changelog của mình (dải số ở AGENTS.md mục 4).

-- ---------------------------------------------------------------- 5. Phạm vi dữ liệu theo trường
--
-- Mọi bảng thuộc trường (phòng, thiết bị, ba loại phiếu, đợt kiểm kê) chạy trên defaultScope = NONE: vai
-- trò chưa có phạm vi thì KHÔNG thấy dòng nào. Seed ở đây cho 5 vai trò:
--   - Sở (SO_LEADER, SO_SPECIALIST): đọc mọi trường; chuyên viên Sở ghi được đợt kiểm kê (Sở phát động).
--   - Trường (SCHOOL_LEADER, SCHOOL_STAFF): chỉ dòng có school.id = trường của tài khoản.
-- Mã quyền chức năng (đọc/ghi/xoá/duyệt) vẫn do changelog 006 quyết; phạm vi chỉ thu hẹp dòng nào.
-- Resource chưa có lớp *Policies thì dòng ở đây được bỏ qua lúc nạp và có hiệu lực ngay khi lớp đó xuất
-- hiện — người phụ trách không phải seed lại.
WITH res(resource) AS (VALUES
    ('rooms'), ('equipment'),
    ('purchase_proposals'), ('equipment_intakes'),
    ('inventory_campaigns'), ('inventory_sessions')),
plan(role_code, action, name, description, scope) AS (VALUES
    ('SO_LEADER',     'read',   'Sở xem mọi trường',   'Sở GD&ĐT tổng hợp dữ liệu toàn ngành.',          '{"all": []}'),
    ('SO_SPECIALIST', 'read',   'Sở xem mọi trường',   'Sở GD&ĐT tổng hợp dữ liệu toàn ngành.',          '{"all": []}'),
    ('SO_SPECIALIST', 'write',  'Sở ghi mọi trường',   'Chuyên viên Sở lập đợt kiểm kê cho các trường.', '{"all": []}'),
    ('SO_SPECIALIST', 'delete', 'Sở xoá mọi trường',   'Chuyên viên Sở xoá đợt kiểm kê chưa phát động.', '{"all": []}'),
    ('SCHOOL_LEADER', 'read',   'Chỉ trường của mình', 'Chỉ dữ liệu của trường mà tài khoản được gán.',
     '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'),
    ('SCHOOL_LEADER', 'write',  'Chỉ trường của mình', 'Chỉ dữ liệu của trường mà tài khoản được gán.',
     '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'),
    ('SCHOOL_STAFF',  'read',   'Chỉ trường của mình', 'Chỉ dữ liệu của trường mà tài khoản được gán.',
     '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'),
    ('SCHOOL_STAFF',  'write',  'Chỉ trường của mình', 'Chỉ dữ liệu của trường mà tài khoản được gán.',
     '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'),
    ('SCHOOL_STAFF',  'delete', 'Chỉ trường của mình', 'Chỉ dữ liệu của trường mà tài khoản được gán.',
     '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'))
INSERT INTO row_level_policy (kind, role_id, resource, action, name, description, scope, created_at)
SELECT 'SCOPE', r.id, res.resource, plan.action, plan.name, plan.description, plan.scope::jsonb, now()
FROM plan
JOIN roles r ON r.code = plan.role_code
CROSS JOIN res
WHERE NOT (plan.role_code = 'SO_SPECIALIST' AND plan.action IN ('write', 'delete')
           AND res.resource <> 'inventory_campaigns')
  AND NOT EXISTS (
      SELECT 1 FROM row_level_policy p
      WHERE p.role_id = r.id AND p.resource = res.resource AND p.action = plan.action);

