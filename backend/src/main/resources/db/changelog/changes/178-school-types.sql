-- Loại hình trường (Công lập, Dân lập, Tư thục) — danh mục dùng chung cùng khuôn cấp học:
-- mã, tên, tên rút gọn, thứ tự, còn dùng, ghi chú. Trường trỏ vào bằng khoá ngoại, cho phép trống
-- (trường cũ chưa khai). RESTRICT như mọi danh mục: loại hình đang có trường dùng thì không xoá được.
CREATE TABLE school_types (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_school_types PRIMARY KEY,
    code          VARCHAR(64)  NOT NULL CONSTRAINT uq_school_types_code UNIQUE,
    name          VARCHAR(255) NOT NULL,
    short_name    VARCHAR(64),
    sort_order    INTEGER,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    note          VARCHAR(500),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE,
    created_by_id BIGINT CONSTRAINT fk_school_types_created_by REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id BIGINT CONSTRAINT fk_school_types_updated_by REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX idx_school_types_sort ON school_types (sort_order, name);

