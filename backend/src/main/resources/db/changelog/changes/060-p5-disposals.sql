INSERT INTO row_level_policy (kind, role_id, resource, action, name, description, scope, created_at)
SELECT 'SCOPE', r.id, 'disposals', plan.action, plan.name, plan.name, plan.scope::jsonb, now()
FROM plan JOIN roles r ON r.code = plan.role_code
WHERE NOT EXISTS (SELECT 1 FROM row_level_policy p
                  WHERE p.role_id = r.id AND p.resource = 'disposals' AND p.action = plan.action);
