CREATE TABLE disposals (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id         BIGINT       NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    code              VARCHAR(32),
    kind              VARCHAR(20)  NOT NULL,
    reason            VARCHAR(30)  NOT NULL,
    proposal_date     DATE         NOT NULL,
    method            VARCHAR(20),
    council           VARCHAR(1000),
    decision_no       VARCHAR(100),
    executed_date     DATE,
    recovered_value   NUMERIC(18, 2),
    disposal_cost     NUMERIC(18, 2),
    minutes_note      VARCHAR(2000),
    source_resource   VARCHAR(60),
    source_id         BIGINT,
    source_code       VARCHAR(40),
    status            VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    approval_step     VARCHAR(20),
    submitted_at      TIMESTAMP WITH TIME ZONE,
    submitted_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    completed_at      TIMESTAMP WITH TIME ZONE,
    completed_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    cancel_reason     VARCHAR(500),
    reject_reason     VARCHAR(500),
    return_note       VARCHAR(500),
    note              VARCHAR(500),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE,
    created_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_disposals_school_code UNIQUE (school_id, code),
    CONSTRAINT ck_disposals_values CHECK (
        (recovered_value IS NULL OR recovered_value >= 0) AND (disposal_cost IS NULL OR disposal_cost >= 0))
);
CREATE INDEX ix_disposals_school ON disposals (school_id, status);

CREATE TABLE disposal_lines (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disposal_id       BIGINT  NOT NULL REFERENCES disposals (id) ON DELETE CASCADE,
    line_no           INTEGER NOT NULL,
    equipment_id      BIGINT  NOT NULL REFERENCES equipment (id) ON DELETE RESTRICT,
    original_value    NUMERIC(18, 2),
    remaining_value   NUMERIC(18, 2),
    note              VARCHAR(255)
);
CREATE INDEX ix_disposal_lines_equipment ON disposal_lines (equipment_id);

INSERT INTO permissions (code, name, description, system_permission)
SELECT 'disposals:' || a.action, a.verb || ' đề nghị thanh lý - ghi giảm', a.description, TRUE
FROM (VALUES
    ('read',    'Xem',   'Xem danh sách và chi tiết'),
    ('write',   'Lập',   'Lập, sửa, trình, ghi biên bản thanh lý'),
    ('delete',  'Xoá',   'Xoá đề nghị nháp'),
    ('export',  'Xuất',  'Xuất dữ liệu ra tệp (PDF, Excel hoặc CSV)'),
    ('approve', 'Duyệt', 'Duyệt đề nghị, quyết định thanh lý, trả lại, từ chối')
) AS a(action, verb, description)
WHERE NOT EXISTS (SELECT 1 FROM permissions p WHERE p.code = 'disposals:' || a.action);

WITH grant_map(role_code, pattern) AS (VALUES
    ('ADMIN', 'disposals:%'),
    ('SCHOOL_STAFF', 'disposals:read'), ('SCHOOL_STAFF', 'disposals:write'),
    ('SCHOOL_STAFF', 'disposals:delete'), ('SCHOOL_STAFF', 'disposals:export'),
    ('SCHOOL_LEADER', 'disposals:read'), ('SCHOOL_LEADER', 'disposals:export'), ('SCHOOL_LEADER', 'disposals:approve'),
    ('UBND_LEADER', 'disposals:read'), ('UBND_LEADER', 'disposals:export'), ('UBND_LEADER', 'disposals:approve'),
    ('UBND_SPECIALIST', 'disposals:read'), ('UBND_SPECIALIST', 'disposals:export'),
    ('SO_LEADER', 'disposals:read'), ('SO_LEADER', 'disposals:export'), ('SO_LEADER', 'disposals:approve'),
    ('SO_SPECIALIST', 'disposals:read'), ('SO_SPECIALIST', 'disposals:export')
)
INSERT INTO role_permissions (role_id, permission_id)
SELECT DISTINCT r.id, p.id
FROM grant_map g JOIN roles r ON r.code = g.role_code JOIN permissions p ON p.code LIKE g.pattern
WHERE NOT EXISTS (SELECT 1 FROM role_permissions rp WHERE rp.role_id = r.id AND rp.permission_id = p.id);

