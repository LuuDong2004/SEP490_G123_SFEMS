INSERT INTO role_permissions (role_id, permission_id)
SELECT rp.role_id, target.id
FROM role_permissions rp
JOIN permissions src ON src.id = rp.permission_id AND src.code IN ('staff:read', 'staff:write', 'staff:delete')
JOIN permissions target ON target.code = 'staff_assignments:' || split_part(src.code, ':', 2)
WHERE NOT EXISTS (SELECT 1 FROM role_permissions x WHERE x.role_id = rp.role_id AND x.permission_id = target.id);
