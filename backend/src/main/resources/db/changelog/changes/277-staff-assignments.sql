-- Hồ sơ cán bộ vẫn một bản lâu dài; staff.main_subject_id / staff_subjects / staff.campus_id giữ làm "phân công hiện tại"
-- (máy chủ ghi kép cho năm học hiện tại). Chuẩn tối thiểu "theo giáo viên" đếm theo phân công của năm được tính.
CREATE TABLE staff_assignments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id       BIGINT NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    school_year_id  BIGINT NOT NULL REFERENCES school_years (id) ON DELETE RESTRICT,
    staff_id        BIGINT NOT NULL REFERENCES staff (id) ON DELETE CASCADE,
    campus_id       BIGINT REFERENCES campuses (id) ON DELETE SET NULL,
    main_subject_id BIGINT REFERENCES subjects (id) ON DELETE RESTRICT,
    note            VARCHAR(500),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at      TIMESTAMP WITH TIME ZONE,
    created_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_staff_assignments_staff_year UNIQUE (staff_id, school_year_id)
);
CREATE INDEX ix_staff_assignments_school_year ON staff_assignments (school_id, school_year_id);

CREATE TABLE staff_assignment_subjects (
    assignment_id BIGINT NOT NULL REFERENCES staff_assignments (id) ON DELETE CASCADE,
    subject_id    BIGINT NOT NULL REFERENCES subjects (id) ON DELETE RESTRICT,
    PRIMARY KEY (assignment_id, subject_id)
);

-- Phân công năm học hiện tại lấy từ hồ sơ cán bộ hiện có: mọi giáo viên đang làm việc.
INSERT INTO staff_assignments (school_id, school_year_id, staff_id, campus_id, main_subject_id, created_at)
SELECT st.school_id, y.id, st.id, st.campus_id, st.main_subject_id, now()
FROM staff st CROSS JOIN school_years y
WHERE y.is_current AND st.active AND st.staff_type = 'TEACHER';

INSERT INTO staff_assignment_subjects (assignment_id, subject_id)
SELECT a.id, ss.subject_id FROM staff_assignments a JOIN staff_subjects ss ON ss.staff_id = a.staff_id
UNION
SELECT a.id, a.main_subject_id FROM staff_assignments a WHERE a.main_subject_id IS NOT NULL;

