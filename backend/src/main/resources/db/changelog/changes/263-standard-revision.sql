-- Một lần sửa danh mục tối thiểu phải có căn cứ. Danh mục mỗi cấp chỉ có MỘT thông tư gốc (TT 37 / 38 / 39 năm 2021);
-- về sau Bộ chỉ SỬA ĐỔI, BỔ SUNG (TT 26/2023) hoặc ĐÍNH CHÍNH (QĐ 1450/2024) nó. Bộ nháp ghi lại lần sửa là loại nào,
-- văn bản nào (một dòng trong chính danh sách văn bản căn cứ của bộ) và lý do (bắt buộc với đính chính).
ALTER TABLE equipment_standards
    ADD COLUMN revision_kind        VARCHAR(16),
    ADD COLUMN revision_document_id BIGINT REFERENCES equipment_standard_documents (id) ON DELETE SET NULL,
    ADD COLUMN revision_note        VARCHAR(500),
    -- Thời điểm XÁC NHẬN: bấm Áp dụng → bộ này dùng để tính đủ / thiếu, báo cáo từ lúc đó; bộ cũ hết hiệu lực cùng lúc.
    ADD COLUMN applied_at           TIMESTAMP WITH TIME ZONE,
    ADD COLUMN retired_at           TIMESTAMP WITH TIME ZONE;
ALTER TABLE equipment_standards
    ADD CONSTRAINT ck_equipment_standards_revision_kind CHECK (revision_kind IN ('AMENDMENT', 'CORRECTION'));

-- Dòng phụ lục khác bộ trước, ghi lúc ÁP DỤNG: thêm / đổi / bỏ — tra lại "văn bản X đã đổi những gì". Ảnh chụp tại lúc
-- áp dụng (tên, chủ đề, số lượng trước → sau), không trỏ sống vào dòng phụ lục: bộ cũ còn đó nhưng dòng bỏ thì không.
CREATE TABLE equipment_standard_changes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    standard_id  BIGINT       NOT NULL REFERENCES equipment_standards (id) ON DELETE CASCADE,
    change_kind  VARCHAR(10)  NOT NULL CHECK (change_kind IN ('ADDED', 'CHANGED', 'REMOVED')),
    subject_id   BIGINT REFERENCES subjects (id) ON DELETE SET NULL,
    norm_id      BIGINT REFERENCES equipment_norms (id) ON DELETE SET NULL,
    name         VARCHAR(500) NOT NULL,
    topic        VARCHAR(1000),
    fields       VARCHAR(500),
    before_text  VARCHAR(500),
    after_text   VARCHAR(500),
    sort_order   INTEGER      NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX idx_equipment_standard_changes_standard ON equipment_standard_changes (standard_id, sort_order);
--rollback DROP TABLE equipment_standard_changes; ALTER TABLE equipment_standards DROP COLUMN retired_at, DROP COLUMN applied_at, DROP COLUMN revision_note, DROP COLUMN revision_document_id, DROP COLUMN revision_kind;
