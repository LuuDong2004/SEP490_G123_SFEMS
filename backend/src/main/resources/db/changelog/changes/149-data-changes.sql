--changeset qltb:149-data-changes
-- Lịch sử thay đổi dữ liệu (QLTB-511, CN-11-11): giá trị TRƯỚC và SAU của các trường quan trọng mỗi lần sửa hồ sơ
-- trường, cơ quan quản lý, cán bộ, phòng, khối nhà, điểm trường, lớp, tổ bộ môn, tài khoản và danh mục dùng chung.
-- Tài sản (equipment_history) và phiếu (voucher_events) đã có lịch sử riêng nên không ghi trùng ở đây.
-- Không khoá ngoại tới users: bảng chỉ thêm, xoá tài khoản không được động vào dòng nào (giữ cả id lẫn tên).
CREATE TABLE data_changes (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    actor_id      BIGINT,
    actor_name    VARCHAR(150),
    resource      VARCHAR(60)   NOT NULL,
    record_id     BIGINT        NOT NULL,
    record_label  VARCHAR(255),
    field         VARCHAR(80)   NOT NULL,
    old_value     VARCHAR(1000),
    new_value     VARCHAR(1000)
);
CREATE INDEX ix_data_changes_record ON data_changes (resource, record_id, created_at);
CREATE INDEX ix_data_changes_created ON data_changes (created_at);
COMMENT ON TABLE data_changes IS 'Lịch sử thay đổi dữ liệu: chỉ thêm, không sửa, không xoá (trigger chặn)';

INSERT INTO permissions (code, name, description, system_permission) VALUES
  ('data_changes:read', 'Xem lịch sử thay đổi dữ liệu', 'Giá trị trước / sau mỗi lần sửa các trường quan trọng', TRUE);
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id FROM roles r JOIN permissions p ON p.code = 'data_changes:read' WHERE r.code = 'ADMIN';

--changeset qltb:149-data-changes-append-only splitStatements:false
-- "Lịch sử chỉ thêm mới, không sửa, không xoá" giữ ở CƠ SỞ DỮ LIỆU, không chỉ ở chỗ API không có nút sửa / xoá.
CREATE FUNCTION data_changes_append_only() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'data_changes chỉ được thêm, không được sửa hoặc xoá';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_data_changes_append_only
    BEFORE UPDATE OR DELETE ON data_changes
    FOR EACH ROW EXECUTE FUNCTION data_changes_append_only();
