--changeset qltb:203-csvc-standards
-- Chuẩn CSVC theo loại × cấp × mức (QLTB-646..649, story QLTB-199): Sở khai, hệ thống chấm từng trường.
-- Căn cứ: TT 13/2020/TT-BGDĐT (tiêu chuẩn CSVC trường MN, TH, THCS, THPT), sửa đổi bởi TT 23/2024/TT-BGDĐT.
--
-- Một dòng = một quy tắc của MỘT loại CSVC (`room_types`) ở MỘT cấp (TH / THCS / THPT) và MỘT mức:
--   MIN    Tiêu chuẩn tối thiểu;  LEVEL1  Tiêu chuẩn mức độ 1;  LEVEL2  Tiêu chuẩn mức độ 2.
-- Các điều kiện đều tuỳ chọn; quy tắc ĐẠT khi mọi điều kiện đã khai đều đạt:
--   min_count         có ít nhất N phòng / hạng mục thuộc loại;
--   count_per_class   số phòng ≥ làm tròn lên(số lớp × tỷ lệ) — vd. 1,0 phòng/lớp;
--   min_room_area     MỖI phòng ≥ X m² (báo phòng nhỏ nhất);
--   area_per_student  tổng diện tích các phòng của loại ≥ số học sinh × X m²;
--   min_total_area    tổng diện tích các phòng của loại ≥ X m².
-- Mức cộng dồn: mức độ 1 gồm cả quy tắc tối thiểu, mức độ 2 gồm cả mức độ 1 (EvaluationService).
--
-- `code` / `name` sinh từ loại + cấp + mức (bảng dựng trên CatalogEntity để dùng chung màn danh mục), không gõ tay.
--
-- SỐ NẠP SẴN DƯỚI ĐÂY LÀ GỢI Ý để Sở rà lại, không phải bộ chuẩn chính thức. Chỉ nạp những điều chắc chắn:
--   - THCS, THPT: phòng học tối thiểu 0,6 phòng/lớp (TT 23/2024 sửa khoản 2 Điều 14, Điều 18);
--   - mức độ 1: 1,0 phòng học/lớp (gợi ý — mỗi lớp một phòng học riêng);
--   - thư viện: 0,60 m²/học sinh, tổng không dưới 54 m² (TH) / 60 m² (THCS, THPT) (Phụ lục II–IV, TT 23/2024) —
--     đặt ở mức độ 1 vì TT 23 dẫn sang tiêu chuẩn thư viện mức độ 1;
--   - phòng nghỉ giáo viên THCS, THPT: tối thiểu 1 phòng, 10 lớp có 1 phòng, 12 m²/phòng (TT 23/2024 sửa khoản 3
--     Điều 16, Điều 20 — mức độ 2);
--   - phòng đa chức năng THCS: tối thiểu 1 phòng;
--   - các khối phòng bắt buộc ở mức tối thiểu (phòng học, hiệu trưởng, phó hiệu trưởng, văn phòng, thư viện, phòng
--     thiết bị giáo dục, y tế, khu vệ sinh học sinh và giáo viên): có ít nhất 1.
-- Chưa nạp (Sở khai trên màn Danh mục chung → Chuẩn CSVC): diện tích phòng học bộ môn từng môn, sân chơi / sân TDTT,
-- khu để xe, nhà ăn, bếp… và TỔNG số phòng học bộ môn (TT 23: TH ≥ 3 / 4, THCS ≥ 4 / 6, THPT ≥ 5 / 6) — điều kiện
-- tính trên NHIỀU loại, chưa có trong mô hình một loại một quy tắc.
CREATE TABLE facility_standard_rules (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_facility_standard_rules PRIMARY KEY,
    code             VARCHAR(64)  NOT NULL CONSTRAINT uq_facility_standard_rules_code UNIQUE,
    name             VARCHAR(255) NOT NULL,
    sort_order       INTEGER,
    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    note             VARCHAR(500),
    room_type_id     BIGINT       NOT NULL
        CONSTRAINT fk_facility_standard_rules_room_type REFERENCES room_types (id) ON DELETE RESTRICT,
    level_code       VARCHAR(10)  NOT NULL
        CONSTRAINT ck_facility_standard_rules_level CHECK (level_code IN ('TH', 'THCS', 'THPT')),
    tier             VARCHAR(10)  NOT NULL
        CONSTRAINT ck_facility_standard_rules_tier CHECK (tier IN ('MIN', 'LEVEL1', 'LEVEL2')),
    min_count        INTEGER
        CONSTRAINT ck_facility_standard_rules_min_count CHECK (min_count IS NULL OR min_count >= 0),
    count_per_class  NUMERIC(6, 3)
        CONSTRAINT ck_facility_standard_rules_per_class CHECK (count_per_class IS NULL OR count_per_class >= 0),
    min_room_area    NUMERIC(10, 2)
        CONSTRAINT ck_facility_standard_rules_room_area CHECK (min_room_area IS NULL OR min_room_area >= 0),
    area_per_student NUMERIC(8, 3)
        CONSTRAINT ck_facility_standard_rules_per_student CHECK (area_per_student IS NULL OR area_per_student >= 0),
    min_total_area   NUMERIC(12, 2)
        CONSTRAINT ck_facility_standard_rules_total_area CHECK (min_total_area IS NULL OR min_total_area >= 0),
    legal_basis      VARCHAR(255),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE,
    created_by_id    BIGINT CONSTRAINT fk_facility_standard_rules_created_by REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id    BIGINT CONSTRAINT fk_facility_standard_rules_updated_by REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_facility_standard_rules_rule UNIQUE (room_type_id, level_code, tier)
);
CREATE INDEX idx_facility_standard_rules_sort ON facility_standard_rules (sort_order, name);
CREATE INDEX idx_facility_standard_rules_level ON facility_standard_rules (level_code);

