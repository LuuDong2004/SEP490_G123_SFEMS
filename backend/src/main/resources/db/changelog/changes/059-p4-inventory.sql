-- ---------------------------------------------------------------- 1. Đợt kiểm kê
--
-- Do Sở (toàn thành phố: managing_body_id là Sở) hoặc UBND (các trường trên địa
-- bàn) phát động. Đợt không chứa dữ liệu kiểm kê — nó là mốc chung để các trường
-- lập phiếu kiểm kê của mình và để cấp trên theo dõi tiến độ.
CREATE TABLE inventory_campaigns (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    managing_body_id  BIGINT       NOT NULL REFERENCES departments_of_education (id) ON DELETE RESTRICT,
    title             VARCHAR(255) NOT NULL,
    cutoff_date       DATE         NOT NULL,
    deadline          DATE         NOT NULL,
    note              VARCHAR(1000),
    closed            BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE,
    created_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_inventory_campaigns_dates CHECK (deadline >= cutoff_date)
);
CREATE INDEX ix_inventory_campaigns_body ON inventory_campaigns (managing_body_id);

-- ---------------------------------------------------------------- 2. Phiếu kiểm kê của trường
CREATE TABLE inventory_sessions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id         BIGINT       NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    campaign_id       BIGINT REFERENCES inventory_campaigns (id) ON DELETE RESTRICT,
    code              VARCHAR(32),
    title             VARCHAR(255) NOT NULL,
    inventory_date    DATE         NOT NULL,
    room_id           BIGINT REFERENCES rooms (id) ON DELETE RESTRICT,
    council           VARCHAR(1000),
    conclusion        VARCHAR(2000),
    status            VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    approval_step     VARCHAR(20),
    submitted_at      TIMESTAMP WITH TIME ZONE,
    submitted_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    completed_at      TIMESTAMP WITH TIME ZONE,
    completed_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    cancel_reason     VARCHAR(500),
    reject_reason     VARCHAR(500),
    return_note       VARCHAR(500),
    note              VARCHAR(500),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE,
    created_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_inventory_sessions_school_code UNIQUE (school_id, code)
);
CREATE INDEX ix_inventory_sessions_school ON inventory_sessions (school_id, status);
CREATE INDEX ix_inventory_sessions_campaign ON inventory_sessions (campaign_id);

-- Một dòng cho mỗi tài sản trên sổ lúc mở phiếu. "Kỳ vọng" là sổ nói gì; "thấy"
-- là tổ kiểm kê thấy gì. found NULL = chưa kiểm tới.
CREATE TABLE inventory_lines (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id          BIGINT  NOT NULL REFERENCES inventory_sessions (id) ON DELETE CASCADE,
    line_no             INTEGER NOT NULL,
    equipment_id        BIGINT  NOT NULL REFERENCES equipment (id) ON DELETE RESTRICT,
    expected_room_id    BIGINT REFERENCES rooms (id) ON DELETE SET NULL,
    expected_condition  VARCHAR(20),
    found               BOOLEAN,
    found_room_id       BIGINT REFERENCES rooms (id) ON DELETE SET NULL,
    found_condition     VARCHAR(20),
    note                VARCHAR(255)
);
CREATE INDEX ix_inventory_lines_session ON inventory_lines (session_id);

-- Tài sản THỪA: thấy thực tế nhưng không có trên sổ.
CREATE TABLE inventory_surplus (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id   BIGINT       NOT NULL REFERENCES inventory_sessions (id) ON DELETE CASCADE,
    line_no      INTEGER      NOT NULL,
    catalog_id   BIGINT       NOT NULL REFERENCES equipment_catalogs (id) ON DELETE RESTRICT,
    name         VARCHAR(255) NOT NULL,
    quantity     INTEGER      NOT NULL CHECK (quantity > 0),
    room_id      BIGINT REFERENCES rooms (id) ON DELETE SET NULL,
    note         VARCHAR(255)
);

-- ---------------------------------------------------------------- 3. Quyền
INSERT INTO permissions (code, name, description, system_permission)
SELECT r.resource || ':' || a.action, a.verb || ' ' || r.label, a.description, TRUE
FROM (VALUES ('inventory_sessions', 'phiếu kiểm kê'), ('inventory_campaigns', 'đợt kiểm kê')) AS r(resource, label)
CROSS JOIN (VALUES
    ('read',    'Xem',   'Xem danh sách và chi tiết'),
    ('write',   'Lập',   'Lập, sửa, ghi kết quả kiểm đếm, trình'),
    ('delete',  'Xoá',   'Xoá bản ghi nháp'),
    ('export',  'Xuất',  'Xuất dữ liệu ra tệp (PDF, Excel hoặc CSV)'),
    ('approve', 'Duyệt', 'Duyệt biên bản kiểm kê, trả lại, từ chối')
) AS a(action, verb, description)
WHERE NOT (r.resource = 'inventory_campaigns' AND a.action = 'approve')
  AND NOT EXISTS (SELECT 1 FROM permissions p WHERE p.code = r.resource || ':' || a.action);

WITH grant_map(role_code, pattern) AS (VALUES
    ('ADMIN', 'inventory_sessions:%'), ('ADMIN', 'inventory_campaigns:%'),
    ('SCHOOL_STAFF', 'inventory_sessions:read'), ('SCHOOL_STAFF', 'inventory_sessions:write'),
    ('SCHOOL_STAFF', 'inventory_sessions:delete'), ('SCHOOL_STAFF', 'inventory_sessions:export'),
    ('SCHOOL_STAFF', 'inventory_campaigns:read'),
    ('SCHOOL_LEADER', 'inventory_sessions:read'), ('SCHOOL_LEADER', 'inventory_sessions:export'),
    ('SCHOOL_LEADER', 'inventory_sessions:approve'), ('SCHOOL_LEADER', 'inventory_campaigns:read'),
    ('UBND_LEADER', 'inventory_sessions:read'), ('UBND_LEADER', 'inventory_campaigns:read'),
    ('UBND_SPECIALIST', 'inventory_sessions:read'), ('UBND_SPECIALIST', 'inventory_sessions:export'),
    ('UBND_SPECIALIST', 'inventory_campaigns:read'), ('UBND_SPECIALIST', 'inventory_campaigns:write'),
    ('UBND_SPECIALIST', 'inventory_campaigns:delete'),
    ('SO_LEADER', 'inventory_sessions:read'), ('SO_LEADER', 'inventory_sessions:export'),
    ('SO_LEADER', 'inventory_campaigns:read'),
    ('SO_SPECIALIST', 'inventory_sessions:read'), ('SO_SPECIALIST', 'inventory_sessions:export'),
    ('SO_SPECIALIST', 'inventory_campaigns:read'), ('SO_SPECIALIST', 'inventory_campaigns:write'),
    ('SO_SPECIALIST', 'inventory_campaigns:delete')
)
INSERT INTO role_permissions (role_id, permission_id)
SELECT DISTINCT r.id, p.id
FROM grant_map g JOIN roles r ON r.code = g.role_code JOIN permissions p ON p.code LIKE g.pattern
WHERE NOT EXISTS (SELECT 1 FROM role_permissions rp WHERE rp.role_id = r.id AND rp.permission_id = p.id);

-- ---------------------------------------------------------------- 4. Phạm vi dữ liệu (phiếu kiểm kê)
--
-- Đợt kiểm kê không phải dữ liệu của một trường, nên không đi qua phạm vi dòng —
-- service lọc theo cơ quan của tài khoản (xem InventoryCampaignService).
WITH plan(role_code, action, name, scope) AS (VALUES
    ('ADMIN', 'read', 'Mọi trường', '{"all": []}'),
    ('ADMIN', 'write', 'Mọi trường', '{"all": []}'),
    ('ADMIN', 'delete', 'Mọi trường', '{"all": []}'),
    ('SO_LEADER', 'read', 'Sở xem mọi trường', '{"all": []}'),
    ('SO_SPECIALIST', 'read', 'Sở xem mọi trường', '{"all": []}'),
    ('UBND_LEADER', 'read', 'UBND xem trường trên địa bàn',
     '{"field": "school.id", "op": "in", "value": {"ctx": "user.managedSchoolIds"}}'),
    ('UBND_SPECIALIST', 'read', 'UBND xem trường trên địa bàn',
     '{"field": "school.id", "op": "in", "value": {"ctx": "user.managedSchoolIds"}}'),
    ('SCHOOL_LEADER', 'read', 'Chỉ trường của mình', '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'),
    ('SCHOOL_STAFF', 'read', 'Chỉ trường của mình', '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'),
    ('SCHOOL_STAFF', 'write', 'Chỉ trường của mình', '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'),
    ('SCHOOL_STAFF', 'delete', 'Chỉ trường của mình', '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'))
INSERT INTO row_level_policy (kind, role_id, resource, action, name, description, scope, created_at)
SELECT 'SCOPE', r.id, 'inventory_sessions', plan.action, plan.name, plan.name, plan.scope::jsonb, now()
FROM plan JOIN roles r ON r.code = plan.role_code
WHERE NOT EXISTS (SELECT 1 FROM row_level_policy p
                  WHERE p.role_id = r.id AND p.resource = 'inventory_sessions' AND p.action = plan.action);
