--comment Bộ tiêu chuẩn thiết bị theo cấp học, văn bản căn cứ và định mức thiết bị.

-- Tham chiếu là khoá ngoại thật (bản Jmix lưu chuỗi mã). Danh mục bị trỏ vào
-- thì RESTRICT: xoá một loại thiết bị đang có định mức là lỗi 409, thao tác
-- đúng là ngừng hoạt động nó.
CREATE TABLE equipment_standards (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                  VARCHAR(64)  NOT NULL,
    name                  VARCHAR(255) NOT NULL,
    sort_order            INTEGER,
    active                BOOLEAN      NOT NULL DEFAULT TRUE,
    note                  VARCHAR(500),
    education_level_id    BIGINT REFERENCES education_levels (id) ON DELETE RESTRICT,
    start_school_year_id  BIGINT REFERENCES school_years (id) ON DELETE RESTRICT,
    end_school_year_id    BIGINT REFERENCES school_years (id) ON DELETE RESTRICT,
    standard_version      VARCHAR(50),
    previous_standard_id  BIGINT REFERENCES equipment_standards (id) ON DELETE SET NULL,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE,
    created_by_id         BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id         BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_equipment_standards_code UNIQUE (code),
    CONSTRAINT ck_equipment_standards_not_self CHECK (previous_standard_id IS NULL OR previous_standard_id <> id)
);

-- Văn bản con: xoá bộ tiêu chuẩn thì xoá theo.
CREATE TABLE equipment_standard_documents (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    standard_id        BIGINT NOT NULL REFERENCES equipment_standards (id) ON DELETE CASCADE,
    document_role      VARCHAR(20)  NOT NULL DEFAULT 'MAIN',
    document_no        VARCHAR(100) NOT NULL,
    document_name      VARCHAR(500),
    issuing_authority  VARCHAR(255),
    issue_date         DATE,
    effective_date     DATE,
    url                VARCHAR(1000),
    sort_order         INTEGER,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE,
    created_by_id      BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id      BIGINT REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX ix_equipment_standard_documents_standard ON equipment_standard_documents (standard_id);

-- Định mức: bộ tiêu chuẩn bị xoá thì các dòng định mức của nó đi theo. Văn
-- bản nguồn bị xoá khỏi bộ thì dòng định mức chỉ mất liên kết, không mất dòng.
CREATE TABLE equipment_norms (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR(64)  NOT NULL,
    name                VARCHAR(255) NOT NULL,
    sort_order          INTEGER,
    active              BOOLEAN      NOT NULL DEFAULT TRUE,
    note                VARCHAR(500),
    standard_id         BIGINT NOT NULL REFERENCES equipment_standards (id) ON DELETE CASCADE,
    equipment_type_id   BIGINT NOT NULL REFERENCES equipment_types (id) ON DELETE RESTRICT,
    subject_id          BIGINT REFERENCES subjects (id) ON DELETE RESTRICT,
    grade_id            BIGINT REFERENCES grades (id) ON DELETE RESTRICT,
    room_type_id        BIGINT REFERENCES room_types (id) ON DELETE RESTRICT,
    min_quantity        INTEGER NOT NULL,
    unit_id             BIGINT REFERENCES units (id) ON DELETE RESTRICT,
    norm_basis          VARCHAR(20) NOT NULL DEFAULT 'PER_CLASS',
    source_document_id  BIGINT REFERENCES equipment_standard_documents (id) ON DELETE SET NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE,
    created_by_id       BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id       BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_equipment_norms_code UNIQUE (code),
    CONSTRAINT ck_equipment_norms_min_quantity CHECK (min_quantity >= 0)
);
CREATE INDEX ix_equipment_norms_standard ON equipment_norms (standard_id);
CREATE INDEX ix_equipment_norms_equipment_type ON equipment_norms (equipment_type_id);
CREATE INDEX ix_equipment_norms_subject ON equipment_norms (subject_id);

