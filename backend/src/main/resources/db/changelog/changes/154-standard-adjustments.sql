-- Điều chỉnh chuẩn thiết bị tối thiểu theo điều kiện thực tế của trường.
--  * Sở quy định THIẾT BỊ NÀO được điều chỉnh và tới đâu, theo cấp học (`standard_adjustment_rules`): cho giảm số
--    lượng (không thấp hơn `reduce_floor` % chuẩn Bộ; tăng thì luôn được), cho thay bằng thiết bị khác trong danh
--    mục theo tỉ lệ Sở đặt (`standard_adjustment_rule_substitutes`), cho trường tự khai thiết bị thay thế ngoài
--    danh mục. Không có dòng quy định = thiết bị bắt buộc theo chuẩn Bộ.
--  * Trường lập MỘT đề nghị nhiều dòng (`standard_adjustments` + `_lines`), mỗi thiết bị một cách điều chỉnh, có
--    lý do; trình cho cơ quan quản lý của trường (UBND với trường UBND quản lý, Sở với trường Sở quản lý). Cơ quan
--    duyệt hoặc trả lại TỪNG dòng; dòng được duyệt có hiệu lực cho tới khi một dòng duyệt sau thay nó, dòng bị trả
--    lại về một đề nghị nháp mới để trường sửa và trình lại.
--  * Chuẩn tối thiểu của trường (`AdequacyService`) tính theo dòng đã duyệt; số theo chuẩn Bộ vẫn giữ bên cạnh.
CREATE TABLE standard_adjustment_rules (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    education_level_id BIGINT NOT NULL REFERENCES education_levels (id) ON DELETE RESTRICT,
    catalog_id         BIGINT NOT NULL REFERENCES equipment_catalogs (id) ON DELETE RESTRICT,
    allow_reduce       BOOLEAN NOT NULL DEFAULT FALSE,
    reduce_floor       INT NOT NULL DEFAULT 50 CHECK (reduce_floor BETWEEN 0 AND 100),
    allow_substitute   BOOLEAN NOT NULL DEFAULT FALSE,
    allow_custom       BOOLEAN NOT NULL DEFAULT FALSE,
    basis              VARCHAR(500),
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_by_id      BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_standard_adjustment_rules UNIQUE (education_level_id, catalog_id),
    CONSTRAINT ck_standard_adjustment_rules_any CHECK (allow_reduce OR allow_substitute OR allow_custom)
);

CREATE TABLE standard_adjustment_rule_substitutes (
    rule_id    BIGINT NOT NULL REFERENCES standard_adjustment_rules (id) ON DELETE CASCADE,
    catalog_id BIGINT NOT NULL REFERENCES equipment_catalogs (id) ON DELETE RESTRICT,
    -- 1 thiết bị gốc = `ratio` thiết bị thay thế.
    ratio      NUMERIC(8, 2) NOT NULL CHECK (ratio > 0),
    PRIMARY KEY (rule_id, catalog_id)
);

CREATE TABLE standard_adjustments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id       BIGINT NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    -- Số đề nghị, cấp lúc trình.
    code            VARCHAR(30),
    status          VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PENDING', 'DONE')),
    note            VARCHAR(1000),
    submitted_at    TIMESTAMP WITH TIME ZONE,
    submitted_by_id BIGINT REFERENCES users (id) ON DELETE SET NULL,
    reviewed_at     TIMESTAMP WITH TIME ZONE,
    reviewed_by_id  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    created_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
-- Mỗi trường tối đa một đề nghị đang mở (nháp hoặc chờ duyệt).
CREATE UNIQUE INDEX uq_standard_adjustments_open ON standard_adjustments (school_id) WHERE status <> 'DONE';
CREATE INDEX ix_standard_adjustments_school ON standard_adjustments (school_id, status);

CREATE TABLE standard_adjustment_lines (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    adjustment_id         BIGINT NOT NULL REFERENCES standard_adjustments (id) ON DELETE CASCADE,
    -- Thiết bị gốc của danh mục tối thiểu.
    catalog_id            BIGINT NOT NULL REFERENCES equipment_catalogs (id) ON DELETE RESTRICT,
    method                VARCHAR(20) NOT NULL CHECK (method IN ('QUANTITY', 'SUBSTITUTE', 'CUSTOM')),
    -- QUANTITY: số phải có mới.
    quantity              INT CHECK (quantity >= 0),
    -- SUBSTITUTE: thiết bị trong danh mục Sở cho thay; CUSTOM: thiết bị ngoài danh mục của chính trường.
    substitute_catalog_id BIGINT REFERENCES equipment_catalogs (id) ON DELETE RESTRICT,
    ratio                 NUMERIC(8, 2) CHECK (ratio > 0),
    reason                VARCHAR(1000) NOT NULL,
    -- Chuẩn Bộ lúc trình — người duyệt so với nó.
    base_required         INT,
    decision              VARCHAR(20) CHECK (decision IN ('APPROVED', 'RETURNED')),
    decision_note         VARCHAR(1000),
    -- Dòng này chép từ dòng bị trả lại nào (để màn trường nhắc lý do trả lại).
    returned_from_id      BIGINT REFERENCES standard_adjustment_lines (id) ON DELETE SET NULL,
    CONSTRAINT uq_standard_adjustment_lines UNIQUE (adjustment_id, catalog_id),
    CONSTRAINT ck_standard_adjustment_lines_shape CHECK (
        (method = 'QUANTITY' AND quantity IS NOT NULL)
        OR (method IN ('SUBSTITUTE', 'CUSTOM') AND substitute_catalog_id IS NOT NULL AND ratio IS NOT NULL))
);
CREATE INDEX ix_standard_adjustment_lines_effective ON standard_adjustment_lines (catalog_id) WHERE decision = 'APPROVED';

