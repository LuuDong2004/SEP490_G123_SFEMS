-- Lưu trữ báo cáo (QLTB-231): báo cáo vốn tính lại mỗi lần xem, số hôm nay khác số tháng trước. "Lưu bản này" chụp
-- lại đúng số liệu lúc lập — tiêu đề, phạm vi, bộ lọc, cột, các dòng — để nộp, đối chiếu, in lại về sau. Bản lưu
-- KHÔNG sửa được (chỉ người lập hoặc quản trị viên xoá). Ai xem được theo nơi lập: Sở thấy mọi bản; cơ quan quản lý
-- thấy bản của mình và của các trường mình quản lý; trường thấy bản của trường mình.
CREATE TABLE report_snapshots (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_name      VARCHAR(60)   NOT NULL,
    title            VARCHAR(300)  NOT NULL,
    subtitle         VARCHAR(500),
    params           JSONB         NOT NULL DEFAULT '{}'::jsonb,
    columns          JSONB         NOT NULL,
    rows             JSONB         NOT NULL,
    row_count        INTEGER       NOT NULL,
    note             VARCHAR(500),
    level            VARCHAR(10)   NOT NULL,
    school_id        BIGINT REFERENCES schools (id) ON DELETE SET NULL,
    body_id          BIGINT REFERENCES departments_of_education (id) ON DELETE SET NULL,
    created_by_id    BIGINT,
    created_by_name  VARCHAR(150),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT ck_report_snapshots_level CHECK (level IN ('CITY', 'BODY', 'SCHOOL'))
);
CREATE INDEX ix_report_snapshots_created ON report_snapshots (created_at);
CREATE INDEX ix_report_snapshots_school ON report_snapshots (school_id);
CREATE INDEX ix_report_snapshots_body ON report_snapshots (body_id);
