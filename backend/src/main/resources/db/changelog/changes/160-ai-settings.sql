-- Cấu hình AI gợi ý (màn Quản trị hệ thống → "Cấu hình AI"): bật / tắt, khoá API (mã hoá bằng SecretBox, không bao
-- giờ trả ra API), mô hình. MỘT dòng duy nhất (id = 1). Khoá để trống thì dùng ANTHROPIC_API_KEY của máy chủ.
CREATE TABLE ai_settings (
    id             SMALLINT      PRIMARY KEY DEFAULT 1,
    enabled        BOOLEAN       NOT NULL DEFAULT FALSE,
    api_key        VARCHAR(2000),
    model          VARCHAR(60)   NOT NULL DEFAULT 'claude-opus-5-5',
    updated_at     TIMESTAMP WITH TIME ZONE,
    updated_by_id  BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_ai_settings_single CHECK (id = 1)
);
COMMENT ON COLUMN ai_settings.api_key IS 'Khoá Anthropic đã mã hoá (SecretBox, AES-GCM) — không bao giờ trả ra API';
INSERT INTO ai_settings (id) VALUES (1);

-- Nhật ký từng lần gọi AI: ai gọi, việc gì, bao nhiêu token — để biết chi phí và ai dùng.
CREATE TABLE ai_calls (
    id             BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    called_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    user_id        BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    feature        VARCHAR(40)   NOT NULL,
    reference      VARCHAR(200),
    model          VARCHAR(60)   NOT NULL,
    rows_sent      INTEGER,
    suggestions    INTEGER,
    input_tokens   INTEGER,
    output_tokens  INTEGER,
    status         VARCHAR(20)   NOT NULL,
    error          VARCHAR(500),
    CONSTRAINT ck_ai_calls_status CHECK (status IN ('OK', 'ERROR'))
);
CREATE INDEX ix_ai_calls_called_at ON ai_calls (called_at DESC);

