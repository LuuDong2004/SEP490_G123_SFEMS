CREATE TABLE semesters (
    id bigint NOT NULL,
    code character varying(64) NOT NULL,
    name character varying(255) NOT NULL,
    school_year_id bigint NOT NULL,
    start_date date NOT NULL,
    end_date date NOT NULL,
    sort_order integer,
    active boolean DEFAULT true NOT NULL,
    note character varying(500),
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone,
    created_by_id bigint,
    updated_by_id bigint,
    CONSTRAINT ck_semesters_dates CHECK (end_date > start_date)
);

ALTER TABLE semesters ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME semesters_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY semesters
    ADD CONSTRAINT pk_semesters PRIMARY KEY (id);

ALTER TABLE ONLY semesters
