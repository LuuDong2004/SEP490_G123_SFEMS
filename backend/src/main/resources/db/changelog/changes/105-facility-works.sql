-- Sổ sửa chữa, cải tạo, nâng cấp CÔNG TRÌNH của trường (QLTB-149; CS-07 trong bảng use case).
--
-- Trước đây hệ thống chỉ theo dõi sửa chữa THIẾT BỊ (phiếu sửa chữa, bảo hành, bảo dưỡng). Sơn lại
-- dãy nhà, chống thấm mái, nâng cấp phòng máy không gắn với một tài sản có mã nào, nên không có chỗ
-- ghi — và "phòng này sửa lần cuối bao giờ, hết bao nhiêu" là câu hỏi không trả lời được.
--
-- Là một SỔ, không phải một phiếu: không có vòng trình - duyệt. Duyệt chi cho một công trình là việc
-- của kế hoạch và hợp đồng, nằm ngoài hệ thống này; ở đây chỉ ghi lại việc đã (hoặc đang) làm.
--
-- Vị trí lồng nhau và tuỳ chọn: phòng ⊂ khối nhà ⊂ cơ sở; để trống cả ba là việc của cả trường.
-- Quyền và phạm vi dòng chép từ `rooms`, như lớp học (088) và tổ bộ môn (102).

--changeset qltb:105-facility-works
CREATE TABLE facility_works (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id       BIGINT       NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    code            VARCHAR(64)  NOT NULL,
    name            VARCHAR(255) NOT NULL,
    sort_order      INTEGER,
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    note            VARCHAR(500),
    work_type       VARCHAR(20)  NOT NULL DEFAULT 'REPAIR',
    campus_id       BIGINT REFERENCES campuses (id) ON DELETE RESTRICT,
    building_id     BIGINT REFERENCES buildings (id) ON DELETE RESTRICT,
    room_id         BIGINT REFERENCES rooms (id) ON DELETE RESTRICT,
    start_date      DATE,
    end_date        DATE,
    cost            NUMERIC(18, 2),
    contractor      VARCHAR(255),
    funding_source  VARCHAR(255),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE,
    created_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_facility_works_school_code UNIQUE (school_id, code),
    CONSTRAINT ck_facility_works_type CHECK (work_type IN ('REPAIR', 'RENOVATION', 'UPGRADE', 'MAINTENANCE')),
    CONSTRAINT ck_facility_works_dates CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date),
    CONSTRAINT ck_facility_works_cost CHECK (cost IS NULL OR cost >= 0)
);
CREATE INDEX ix_facility_works_school ON facility_works (school_id);
CREATE INDEX ix_facility_works_building ON facility_works (building_id);
CREATE INDEX ix_facility_works_room ON facility_works (room_id);

INSERT INTO permissions (code, name, description, system_permission) VALUES
  ('facility_works:read',   'Xem sửa chữa, cải tạo công trình', 'Xem sổ sửa chữa, cải tạo, nâng cấp công trình của trường', TRUE),
  ('facility_works:write',  'Ghi sửa chữa, cải tạo công trình', 'Thêm, sửa một lần sửa chữa, cải tạo, nâng cấp công trình', TRUE),
  ('facility_works:delete', 'Xoá sửa chữa, cải tạo công trình', 'Xoá vĩnh viễn một dòng của sổ sửa chữa, cải tạo', TRUE);

-- Vai trò nào có rooms:X thì có facility_works:X.
INSERT INTO role_permissions (role_id, permission_id)
SELECT rp.role_id, target.id
FROM role_permissions rp
JOIN permissions src ON src.id = rp.permission_id AND src.code LIKE 'rooms:%'
JOIN permissions target ON target.code = 'facility_works:' || split_part(src.code, ':', 2);

INSERT INTO row_level_policy (kind, role_id, resource, action, name, policy_group, description, scope, check_scope, enabled, created_at)
SELECT kind, role_id, 'facility_works', action, name, policy_group, description, scope, check_scope, enabled, now()
FROM row_level_policy
WHERE resource = 'rooms';

