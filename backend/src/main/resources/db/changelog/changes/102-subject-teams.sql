-- Tổ bộ môn của trường (Tổ Toán - Tin, Tổ Khoa học tự nhiên…): tổ trưởng, các môn tổ phụ trách, và
-- giáo viên thuộc tổ. Trước đây "tổ" chỉ là một ô chữ gõ tự do trên hồ sơ cán bộ (staff.department)
-- — không đếm được, không chọn được ở chỗ khác, và hai người gõ "Tổ KHTN" / "Tổ Khoa học tự nhiên"
-- thành hai tổ.
--
-- Một giáo viên thuộc MỘT tổ: bảng thành viên có unique (staff_id). Thêm giáo viên vào tổ khác là
-- chuyển tổ, do service làm.
--
-- Quyền và phạm vi dòng chép từ `rooms`, như lớp học (088) — tổ bộ môn cũng là dữ liệu tổ chức của
-- trường, cùng một người quản.

--changeset qltb:102-subject-teams
CREATE TABLE subject_teams (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id      BIGINT       NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    code           VARCHAR(64)  NOT NULL,
    name           VARCHAR(255) NOT NULL,
    sort_order     INTEGER,
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    note           VARCHAR(500),
    leader_id      BIGINT REFERENCES staff (id) ON DELETE SET NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE,
    created_by_id  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_subject_teams_school_code UNIQUE (school_id, code)
);
CREATE INDEX ix_subject_teams_school ON subject_teams (school_id);

CREATE TABLE subject_team_subjects (
    team_id     BIGINT NOT NULL REFERENCES subject_teams (id) ON DELETE CASCADE,
    subject_id  BIGINT NOT NULL REFERENCES subjects (id) ON DELETE RESTRICT,
    PRIMARY KEY (team_id, subject_id)
);

CREATE TABLE subject_team_members (
    team_id   BIGINT NOT NULL REFERENCES subject_teams (id) ON DELETE CASCADE,
    staff_id  BIGINT NOT NULL REFERENCES staff (id) ON DELETE CASCADE,
    PRIMARY KEY (team_id, staff_id),
    CONSTRAINT uq_subject_team_members_staff UNIQUE (staff_id)
);

INSERT INTO permissions (code, name, description, system_permission) VALUES
