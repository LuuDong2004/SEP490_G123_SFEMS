ALTER TABLE school_code_rules
    ADD CONSTRAINT ck_school_code_rules_target
        CHECK (target IN ('rooms', 'buildings', 'campuses', 'staff', 'subject_teams'));

-- Tổ đã có trong ô chữ tự do của cán bộ ("Tổ Toán - Tin"…) thành tổ thật: mỗi (trường, tên tổ) một
-- tổ, giáo viên mang tên tổ ấy là thành viên, môn của tổ là môn chính của các thành viên.
--changeset qltb:102-subject-teams-from-department
INSERT INTO subject_teams (school_id, code, name, sort_order, active, created_at)
SELECT d.school_id,
       'TO' || lpad(row_number() OVER (PARTITION BY d.school_id ORDER BY d.name)::text, 2, '0'),
       d.name,
       row_number() OVER (PARTITION BY d.school_id ORDER BY d.name),
       TRUE,
       now()
FROM (SELECT DISTINCT st.school_id, btrim(st.department) AS name
      FROM staff st
      WHERE st.active AND st.staff_type = 'TEACHER' AND btrim(st.department) ILIKE 'tổ %') d;

INSERT INTO subject_team_members (team_id, staff_id)
SELECT t.id, st.id
FROM staff st
JOIN subject_teams t ON t.school_id = st.school_id AND t.name = btrim(st.department)
WHERE st.active AND st.staff_type = 'TEACHER';

INSERT INTO subject_team_subjects (team_id, subject_id)
SELECT DISTINCT m.team_id, st.main_subject_id
FROM subject_team_members m
JOIN staff st ON st.id = m.staff_id
WHERE st.main_subject_id IS NOT NULL;
