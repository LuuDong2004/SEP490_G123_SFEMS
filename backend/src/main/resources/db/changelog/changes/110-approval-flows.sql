-- Luồng phê duyệt do Sở cấu hình.
--
-- Trước changelog này các bước duyệt của mỗi loại phiếu viết cứng trong code (`approvalChain()` của từng
-- phiếu): muốn "thanh lý dưới 10 triệu chỉ cần trường duyệt" là phải sửa code và triển khai lại. Ai duyệt
-- ở mỗi bước thì vẫn đã cấu hình được từ trước (vai trò + mã quyền `<loại phiếu>:approve`).
--
-- Từ đây mỗi loại phiếu có thể có MỘT dòng cấu hình: các bước (theo thứ tự cấp: SCHOOL → MANAGING_BODY →
-- RECEIVING_BODY), và tuỳ chọn một ngưỡng tiền — phiếu từ ngưỡng trở lên đi theo các bước khác. Loại phiếu
-- không có dòng chạy luồng mặc định trong code (`ApprovalFlowType`), nên changelog này không seed dòng nào:
-- bật tính năng không đổi luồng của phiếu nào.
--
-- Luật nghiệp vụ theo nội dung phiếu (báo hỏng tự sửa, sửa chữa tại chỗ… không cần duyệt) KHÔNG nằm ở đây:
-- chúng ở trên chính phiếu (`approvalExempt()`), Sở không đè được.

--changeset qltb:110-approval-flows

CREATE TABLE approval_flows (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource         VARCHAR(60)  NOT NULL,
    steps            VARCHAR(100) NOT NULL DEFAULT '',
    amount_threshold NUMERIC(18, 2),
    steps_above      VARCHAR(100),
    note             VARCHAR(500),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE,
    created_by_id    BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id    BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_approval_flows_resource UNIQUE (resource),
    CONSTRAINT ck_approval_flows_threshold CHECK (amount_threshold IS NULL OR amount_threshold > 0),
    -- Có ngưỡng thì phải nói từ ngưỡng trở lên đi theo bước nào.
    CONSTRAINT ck_approval_flows_above CHECK ((amount_threshold IS NULL) = (steps_above IS NULL))
);

COMMENT ON TABLE approval_flows IS 'Luồng phê duyệt Sở cấu hình cho từng loại phiếu; không có dòng = luồng mặc định trong code';
COMMENT ON COLUMN approval_flows.steps IS 'Các bước, mã ngăn bằng dấu phẩy, theo thứ tự cấp: SCHOOL,MANAGING_BODY,RECEIVING_BODY; rỗng = trình là xong';
COMMENT ON COLUMN approval_flows.steps_above IS 'Các bước cho phiếu có số tiền từ amount_threshold trở lên';

INSERT INTO permissions (code, name, description, system_permission) VALUES
  ('approval_flows:read',  'Xem luồng phê duyệt', 'Xem các bước duyệt của từng loại phiếu', TRUE),
  ('approval_flows:write', 'Sửa luồng phê duyệt', 'Đổi các bước duyệt và ngưỡng tiền của từng loại phiếu', TRUE);

-- Sở cấu hình (chuyên viên Sở) và quản trị viên. Trường và UBND không: luồng duyệt là quy định chung của
-- ngành, không phải lựa chọn của đơn vị bị duyệt.
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN permissions p ON p.code IN ('approval_flows:read', 'approval_flows:write')
WHERE r.code IN ('ADMIN', 'SO_SPECIALIST');
