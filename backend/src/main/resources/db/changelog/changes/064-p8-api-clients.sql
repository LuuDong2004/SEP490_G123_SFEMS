CREATE TABLE api_clients (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(255) NOT NULL,
    description    VARCHAR(1000),
    user_id        BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    key_prefix     VARCHAR(16)  NOT NULL,
    key_hash       VARCHAR(64)  NOT NULL UNIQUE,
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    expires_at     TIMESTAMP WITH TIME ZONE,
    last_used_at   TIMESTAMP WITH TIME ZONE,
    last_used_ip   VARCHAR(64),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE,
    created_by_id  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id  BIGINT REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX ix_api_clients_user ON api_clients (user_id);

INSERT INTO permissions (code, name, description, system_permission)
SELECT v.code, v.name, v.description, TRUE
FROM (VALUES
    ('api_clients:read',   'Xem khoá API',  'Xem danh sách hệ thống tích hợp và khoá API'),
    ('api_clients:write',  'Cấp khoá API',  'Cấp, thu hồi khoá API cho hệ thống tích hợp'),
    ('api_clients:delete', 'Xoá khoá API',  'Xoá khoá API')
) AS v(code, name, description)
WHERE NOT EXISTS (SELECT 1 FROM permissions p WHERE p.code = v.code);

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id FROM roles r JOIN permissions p ON p.code LIKE 'api_clients:%'
WHERE r.code = 'ADMIN'
  AND NOT EXISTS (SELECT 1 FROM role_permissions rp WHERE rp.role_id = r.id AND rp.permission_id = p.id);
