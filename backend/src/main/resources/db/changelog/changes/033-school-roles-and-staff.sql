-- ADMIN: toàn quyền. SCHOOL_ADMIN: toàn quyền trên trường mình. MANAGER (Sở),
-- EQUIPMENT_OFFICER, USER: chỉ xem.
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id FROM roles r
JOIN permissions p ON p.code IN ('staff:read', 'staff:write', 'staff:delete')
WHERE r.code IN ('ADMIN', 'SCHOOL_ADMIN');

