-- ============================================================================
-- Cán bộ, giáo viên. Mã duy nhất TRONG trường.
-- ============================================================================
CREATE TABLE staff (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id        BIGINT NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    code             VARCHAR(64)  NOT NULL,
    name             VARCHAR(255) NOT NULL,
    sort_order       INTEGER,
    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    note             VARCHAR(500),
    staff_type       VARCHAR(20)  NOT NULL DEFAULT 'TEACHER',
    position         VARCHAR(40),
    department       VARCHAR(255),
    phone            VARCHAR(30),
    email            VARCHAR(255),
    main_subject_id  BIGINT REFERENCES subjects (id) ON DELETE RESTRICT,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE,
    created_by_id    BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id    BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_staff_school_code UNIQUE (school_id, code)
);
CREATE INDEX ix_staff_school ON staff (school_id);

CREATE TABLE staff_subjects (
    staff_id    BIGINT NOT NULL REFERENCES staff (id) ON DELETE CASCADE,
    subject_id  BIGINT NOT NULL REFERENCES subjects (id) ON DELETE RESTRICT,
    CONSTRAINT pk_staff_subjects PRIMARY KEY (staff_id, subject_id)
);

