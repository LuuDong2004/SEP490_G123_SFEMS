CREATE TABLE equipment_intake_documents (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intake_id             BIGINT       NOT NULL REFERENCES equipment_intakes (id) ON DELETE CASCADE,
    doc_no                INTEGER      NOT NULL,
    supplier              VARCHAR(255),
    tax_code              VARCHAR(20),
    document_no           VARCHAR(100),
    document_date         DATE,
    funding_source        VARCHAR(30),
    funding_note          VARCHAR(255),
    acquisition_method_id BIGINT REFERENCES acquisition_methods (id) ON DELETE RESTRICT,
    acquisition_note      VARCHAR(255),
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE,
    created_by_id         BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id         BIGINT REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX ix_equipment_intake_documents_intake ON equipment_intake_documents (intake_id);

ALTER TABLE equipment_intake_lines
    ADD COLUMN document_id BIGINT REFERENCES equipment_intake_documents (id) ON DELETE SET NULL;
CREATE INDEX ix_equipment_intake_lines_document ON equipment_intake_lines (document_id);

-- Phiếu đã có: mỗi bộ chứng từ THẬT của dòng (của dòng, không thì của đầu phiếu) thành một hoá đơn, theo thứ tự dòng.
INSERT INTO equipment_intake_documents (intake_id, doc_no, supplier, document_no, document_date, funding_source,
                                        funding_note, acquisition_method_id, acquisition_note, created_at)
SELECT g.intake_id,
       ROW_NUMBER() OVER (PARTITION BY g.intake_id ORDER BY g.first_line),
       g.supplier, g.document_no, g.document_date, g.funding_source, g.funding_note, g.acquisition_method_id,
       g.acquisition_note, NOW()
FROM (SELECT l.intake_id,
             COALESCE(l.supplier, i.supplier)                           AS supplier,
             COALESCE(l.document_no, i.document_no)                     AS document_no,
             COALESCE(l.document_date, i.document_date)                 AS document_date,
             COALESCE(l.funding_source, i.funding_source)               AS funding_source,
             l.funding_note,
             COALESCE(l.acquisition_method_id, i.acquisition_method_id) AS acquisition_method_id,
             l.acquisition_note,
             MIN(l.line_no)                                             AS first_line
      FROM equipment_intake_lines l
               JOIN equipment_intakes i ON i.id = l.intake_id
      GROUP BY l.intake_id, 2, 3, 4, 5, 6, 7, 8) g;

UPDATE equipment_intake_lines l
SET document_id = d.id
FROM equipment_intakes i, equipment_intake_documents d
WHERE i.id = l.intake_id
  AND d.intake_id = l.intake_id
  AND d.supplier IS NOT DISTINCT FROM COALESCE(l.supplier, i.supplier)
  AND d.document_no IS NOT DISTINCT FROM COALESCE(l.document_no, i.document_no)
  AND d.document_date IS NOT DISTINCT FROM COALESCE(l.document_date, i.document_date)
  AND d.funding_source IS NOT DISTINCT FROM COALESCE(l.funding_source, i.funding_source)
  AND d.funding_note IS NOT DISTINCT FROM l.funding_note
  AND d.acquisition_method_id IS NOT DISTINCT FROM COALESCE(l.acquisition_method_id, i.acquisition_method_id)
  AND d.acquisition_note IS NOT DISTINCT FROM l.acquisition_note;

-- Tệp hoá đơn từng gắn theo dòng đi theo hoá đơn của dòng đó.
UPDATE attachments a
SET resource = 'equipment_intake_documents', record_id = l.document_id
FROM equipment_intake_lines l
WHERE a.resource = 'equipment_intake_lines'
  AND a.record_id = l.id
  AND l.document_id IS NOT NULL;
