-- Điều chỉnh CHUẨN CSVC TỐI THIỂU theo điều kiện thực tế của trường — cùng khuôn với điều chỉnh chuẩn thiết bị (154).
--  * Trường lập MỘT đề nghị nhiều dòng; mỗi dòng một loại CSVC có chuẩn tối thiểu: số phòng phải có mới và / hoặc tổng
--    diện tích phải có mới, kèm lý do (vd. trường nội thành thiếu đất). Trình cho cơ quan quản lý của trường.
--  * Cơ quan quản lý duyệt hoặc trả lại TỪNG dòng. Dòng duyệt có hiệu lực tới khi một dòng duyệt sau thay nó; dòng
--    trả lại chép sang bản nháp mới để trường sửa, trình lại.
--  * Chấm chuẩn của trường: mức TỐI THIỂU của loại đó tính theo số đã duyệt; mức độ 1, 2 giữ chuẩn chung của Sở.
CREATE TABLE facility_standard_adjustments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id       BIGINT NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    code            VARCHAR(30),
    status          VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PENDING', 'DONE')),
    note            VARCHAR(1000),
    submitted_at    TIMESTAMP WITH TIME ZONE,
    submitted_by_id BIGINT REFERENCES users (id) ON DELETE SET NULL,
    reviewed_at     TIMESTAMP WITH TIME ZONE,
    reviewed_by_id  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    created_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_facility_standard_adjustments_open ON facility_standard_adjustments (school_id)
    WHERE status <> 'DONE';

CREATE TABLE facility_standard_adjustment_lines (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    adjustment_id    BIGINT NOT NULL REFERENCES facility_standard_adjustments (id) ON DELETE CASCADE,
    room_type_id     BIGINT NOT NULL REFERENCES room_types (id) ON DELETE RESTRICT,
    -- Số phòng / tổng diện tích phải có MỚI ở mức tối thiểu; trống = giữ chuẩn chung cho điều kiện đó.
    required_count   INT CHECK (required_count >= 0),
    required_area    NUMERIC(12, 2) CHECK (required_area >= 0),
    reason           VARCHAR(1000) NOT NULL,
    -- Chuẩn chung lúc trình — người duyệt so với nó.
    base_count       INT,
    base_area        NUMERIC(12, 2),
    decision         VARCHAR(20) CHECK (decision IN ('APPROVED', 'RETURNED')),
    decision_note    VARCHAR(1000),
    returned_from_id BIGINT REFERENCES facility_standard_adjustment_lines (id) ON DELETE SET NULL,
    CONSTRAINT uq_facility_standard_adjustment_lines UNIQUE (adjustment_id, room_type_id),
    CONSTRAINT ck_facility_standard_adjustment_lines_any CHECK (required_count IS NOT NULL OR required_area IS NOT NULL)
);

