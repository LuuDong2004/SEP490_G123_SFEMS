CREATE INDEX ix_equipment_intake_lines_intake ON equipment_intake_lines (intake_id);
CREATE INDEX ix_equipment_intake_lines_catalog ON equipment_intake_lines (catalog_id);

-- ---------------------------------------------------------------- 6. Hồ sơ thiết bị (TS-01..TS-06)
--
-- code là mã tài sản chuẩn TT.TR.MH.LT.ST.NC (TS-06), duy nhất trong trường. intake_line_id trỏ về
-- dòng phiếu nhập đã sinh ra nó (PN-03); RESTRICT để không xoá được phiếu đã ghi tăng.
CREATE TABLE equipment (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id              BIGINT       NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    code                   VARCHAR(64)  NOT NULL,
    name                   VARCHAR(255) NOT NULL,
    sort_order             INTEGER,
    active                 BOOLEAN      NOT NULL DEFAULT TRUE,
    note                   VARCHAR(500),
    catalog_id             BIGINT       NOT NULL REFERENCES equipment_catalogs (id) ON DELETE RESTRICT,
    physical_or_digital    VARCHAR(20)  NOT NULL DEFAULT 'PHYSICAL',
    asset_category         VARCHAR(30),
    legacy_code            VARCHAR(64),
    serial_number          VARCHAR(100),
    model                  VARCHAR(255),
    manufacturer           VARCHAR(255),
    unit_id                BIGINT REFERENCES units (id) ON DELETE RESTRICT,
    quantity               NUMERIC(14, 3) NOT NULL DEFAULT 1,
    origin_source_id       BIGINT REFERENCES origin_sources (id) ON DELETE RESTRICT,
    acquisition_method_id  BIGINT REFERENCES acquisition_methods (id) ON DELETE RESTRICT,
    funding_source         VARCHAR(30),
    origin_note            VARCHAR(255),
    funding_note           VARCHAR(255),
    acquisition_note       VARCHAR(255),
    production_year        INTEGER,
    usage_start_year       INTEGER,
    received_date          DATE,
    purchase_date          DATE,
    original_value         NUMERIC(18, 2),
    remaining_value        NUMERIC(18, 2),
    warranty_expiry        DATE,
    room_id                BIGINT REFERENCES rooms (id) ON DELETE SET NULL,
    manager_id             BIGINT REFERENCES users (id) ON DELETE SET NULL,
    condition              VARCHAR(20),
    status                 VARCHAR(30)  NOT NULL DEFAULT 'IN_USE',
    specs                  JSONB        NOT NULL DEFAULT '{}'::jsonb,
    intake_line_id         BIGINT REFERENCES equipment_intake_lines (id) ON DELETE RESTRICT,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at             TIMESTAMP WITH TIME ZONE,
    created_by_id          BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id          BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_equipment_school_code UNIQUE (school_id, code),
    CONSTRAINT ck_equipment_quantity CHECK (quantity > 0),
    CONSTRAINT ck_equipment_values CHECK (original_value IS NULL OR original_value >= 0),
    CONSTRAINT ck_equipment_remaining CHECK (remaining_value IS NULL OR remaining_value >= 0)
);
CREATE INDEX ix_equipment_school ON equipment (school_id, status);
CREATE INDEX ix_equipment_catalog ON equipment (catalog_id);
CREATE INDEX ix_equipment_room ON equipment (room_id);
CREATE INDEX ix_equipment_intake_line ON equipment (intake_line_id);
