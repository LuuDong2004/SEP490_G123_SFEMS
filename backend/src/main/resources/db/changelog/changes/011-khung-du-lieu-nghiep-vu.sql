-- ---------------------------------------------------------------- 5. Phiếu nhập (PN-01..PN-03)
--
-- Cột chung của mọi phiếu theo ghi chú ở changelog 010 mục 4. Thông tin chung (nhà cung cấp, chứng
-- từ, nguồn, bảo hành) ở đầu phiếu; dòng khai riêng khi khác đi.
CREATE TABLE equipment_intakes (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id              BIGINT       NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    code                   VARCHAR(32),
    status                 VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    approval_step          VARCHAR(20),
    reached_step           VARCHAR(20),
    submitted_at           TIMESTAMP WITH TIME ZONE,
    submitted_by_id        BIGINT REFERENCES users (id) ON DELETE SET NULL,
    completed_at           TIMESTAMP WITH TIME ZONE,
    completed_by_id        BIGINT REFERENCES users (id) ON DELETE SET NULL,
    cancel_reason          VARCHAR(500),
    reject_reason          VARCHAR(500),
    return_note            VARCHAR(500),
    note                   VARCHAR(500),
    intake_date            DATE         NOT NULL,
    document_no            VARCHAR(100),
    document_date          DATE,
    supplier               VARCHAR(255),
    funding_source         VARCHAR(30),
    origin_source_id       BIGINT REFERENCES origin_sources (id) ON DELETE RESTRICT,
    origin_note            VARCHAR(255),
    acquisition_method_id  BIGINT REFERENCES acquisition_methods (id) ON DELETE RESTRICT,
    school_year_id         BIGINT REFERENCES school_years (id) ON DELETE RESTRICT,
    warranty_months        INTEGER,
    source_resource        VARCHAR(40),
    source_id              BIGINT,
    source_code            VARCHAR(50),
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at             TIMESTAMP WITH TIME ZONE,
    created_by_id          BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id          BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_equipment_intakes_school_code UNIQUE (school_id, code),
    CONSTRAINT ck_equipment_intakes_warranty CHECK (warranty_months IS NULL OR warranty_months >= 0),
    -- Phiếu đã hoàn tất (đã ghi tăng) thì PHẢI có số phiếu và thời điểm hoàn tất.
    CONSTRAINT ck_equipment_intakes_completed CHECK (
        status <> 'COMPLETED' OR (code IS NOT NULL AND completed_at IS NOT NULL))
);
CREATE INDEX ix_equipment_intakes_school ON equipment_intakes (school_id, status);
CREATE INDEX ix_equipment_intakes_date ON equipment_intakes (intake_date);

