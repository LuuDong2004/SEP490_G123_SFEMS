    campaign_id       BIGINT REFERENCES inventory_campaigns (id) ON DELETE RESTRICT,
    title             VARCHAR(255) NOT NULL,
    inventory_date    DATE         NOT NULL,
    room_id           BIGINT REFERENCES rooms (id) ON DELETE RESTRICT,
    council           VARCHAR(1000),
    conclusion        VARCHAR(2000),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE,
    created_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_inventory_sessions_school_code UNIQUE (school_id, code)
);
CREATE INDEX ix_inventory_sessions_school ON inventory_sessions (school_id, status);
CREATE INDEX ix_inventory_sessions_campaign ON inventory_sessions (campaign_id);

-- Một dòng cho mỗi tài sản trên sổ lúc mở phiếu. expected_* là sổ nói gì, found_* là thấy gì; found
-- NULL = chưa kiểm tới.
CREATE TABLE inventory_lines (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id          BIGINT  NOT NULL REFERENCES inventory_sessions (id) ON DELETE CASCADE,
    line_no             INTEGER NOT NULL,
    equipment_id        BIGINT  NOT NULL REFERENCES equipment (id) ON DELETE RESTRICT,
    expected_room_id    BIGINT REFERENCES rooms (id) ON DELETE SET NULL,
    expected_condition  VARCHAR(20),
    found               BOOLEAN,
    found_room_id       BIGINT REFERENCES rooms (id) ON DELETE SET NULL,
    found_condition     VARCHAR(20),
    note                VARCHAR(255),
    CONSTRAINT uq_inventory_lines_no UNIQUE (session_id, line_no)
);
CREATE INDEX ix_inventory_lines_session ON inventory_lines (session_id);
CREATE INDEX ix_inventory_lines_equipment ON inventory_lines (equipment_id);

-- Tài sản THỪA: thấy thực tế nhưng không có trên sổ.
CREATE TABLE inventory_surplus (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id   BIGINT       NOT NULL REFERENCES inventory_sessions (id) ON DELETE CASCADE,
    line_no      INTEGER      NOT NULL,
    catalog_id   BIGINT       NOT NULL REFERENCES equipment_catalogs (id) ON DELETE RESTRICT,
    name         VARCHAR(255) NOT NULL,
    quantity     INTEGER      NOT NULL,
    room_id      BIGINT REFERENCES rooms (id) ON DELETE SET NULL,
    note         VARCHAR(255),
    CONSTRAINT uq_inventory_surplus_no UNIQUE (session_id, line_no),
    CONSTRAINT ck_inventory_surplus_qty CHECK (quantity > 0)
);

-- ---------------------------------------------------------------- 9. Thông báo (HT-06)
--
-- Mỗi dòng cho MỘT người nhận; thông báo cho một nhóm là chừng ấy dòng. Xoá tài khoản thì xoá theo.
CREATE TABLE notifications (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id  BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    level         VARCHAR(32)  NOT NULL DEFAULT 'INFO',
    title         VARCHAR(255) NOT NULL,
    body          VARCHAR(2000),
    link          VARCHAR(500),
    read_at       TIMESTAMP WITH TIME ZONE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_notifications_recipient ON notifications (recipient_id, read_at, created_at DESC);

-- ---------------------------------------------------------------- 10. Tệp đính kèm (TS-03)
--
-- Gắn bằng (resource, record_id), không khoá ngoại: một bảng cho mọi loại bản ghi. Nội dung ở MinIO.
CREATE TABLE attachments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource       VARCHAR(60)  NOT NULL,
    record_id      BIGINT       NOT NULL,
    file_name      VARCHAR(255) NOT NULL,
    content_type   VARCHAR(120) NOT NULL,
    size_bytes     BIGINT       NOT NULL,
    storage_key    VARCHAR(300) NOT NULL,
    note           VARCHAR(255),
    is_cover       BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE,
    created_by_id  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_attachments_storage_key UNIQUE (storage_key),
    CONSTRAINT ck_attachments_size CHECK (size_bytes >= 0)
);
CREATE INDEX ix_attachments_record ON attachments (resource, record_id);
-- Mỗi bản ghi tối đa MỘT ảnh đại diện.
CREATE UNIQUE INDEX uq_attachments_cover ON attachments (resource, record_id) WHERE is_cover;

