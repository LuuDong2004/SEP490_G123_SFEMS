-- Quy ước chung của mọi bảng ở đây:
--   * Khoá ngoại RESTRICT trừ khi ghi khác: không xoá được thứ còn được tham chiếu (BaseEntity không
--     có xoá mềm). Dòng của một phiếu là THÀNH PHẦN của phiếu nên CASCADE theo phiếu.
--   * created_by_id / updated_by_id trỏ users với SET NULL — tài khoản nghỉ việc không chặn gì.
--   * Mã của dữ liệu thuộc trường (phòng, thiết bị, số phiếu) chỉ duy nhất TRONG trường: UNIQUE
--     (school_id, code). Danh mục của Sở duy nhất toàn hệ thống: UNIQUE (code).
--   * Cột trạng thái lưu TÊN hằng của enum Java (varchar), nhãn tiếng Việt ở frontend.

-- ---------------------------------------------------------------- 1. Danh mục thiết bị (DM-02)
--
-- Cây nhóm thiết bị của Sở; mỗi thiết bị của trường thuộc một nút. owner_school_id có giá trị là
-- nhóm NGOÀI danh mục do riêng trường ấy thêm (tự làm, tài trợ...) — khi đó origin bắt buộc.
CREATE TABLE equipment_catalogs (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                 VARCHAR(64)  NOT NULL,
    name                 VARCHAR(255) NOT NULL,
    sort_order           INTEGER,
    active               BOOLEAN      NOT NULL DEFAULT TRUE,
    note                 VARCHAR(500),
    teaching_code        VARCHAR(3),
    parent_id            BIGINT REFERENCES equipment_catalogs (id) ON DELETE RESTRICT,
    equipment_type_id    BIGINT REFERENCES equipment_types (id) ON DELETE RESTRICT,
    subject_id           BIGINT REFERENCES subjects (id) ON DELETE RESTRICT,
    education_level_id   BIGINT REFERENCES education_levels (id) ON DELETE RESTRICT,
    grade_id             BIGINT REFERENCES grades (id) ON DELETE RESTRICT,
    unit_id              BIGINT REFERENCES units (id) ON DELETE RESTRICT,
    model                VARCHAR(255),
    manufacturer         VARCHAR(255),
    tracking_type        VARCHAR(20)  NOT NULL DEFAULT 'SERIAL',
    asset_category       VARCHAR(30),
    physical_or_digital  VARCHAR(30),
    useful_life_years    INTEGER,
    minimum_required     BOOLEAN      NOT NULL DEFAULT FALSE,
    statistical_code     VARCHAR(64),
    legal_basis          VARCHAR(255),
    description          TEXT,
    used_by_teacher      BOOLEAN      NOT NULL DEFAULT FALSE,
    used_by_student      BOOLEAN      NOT NULL DEFAULT FALSE,
    owner_school_id      BIGINT REFERENCES schools (id) ON DELETE RESTRICT,
    origin               VARCHAR(30),
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at           TIMESTAMP WITH TIME ZONE,
    created_by_id        BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id        BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_equipment_catalogs_code UNIQUE (code),
    CONSTRAINT ck_equipment_catalogs_not_self CHECK (parent_id IS NULL OR parent_id <> id),
    CONSTRAINT ck_equipment_catalogs_teaching_code CHECK (teaching_code IS NULL OR teaching_code ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_equipment_catalogs_useful_life CHECK (useful_life_years IS NULL OR useful_life_years BETWEEN 0 AND 100),
    CONSTRAINT ck_equipment_catalogs_owner_origin CHECK (owner_school_id IS NULL OR origin IS NOT NULL)
);
CREATE INDEX ix_equipment_catalogs_parent ON equipment_catalogs (parent_id);
CREATE INDEX ix_equipment_catalogs_subject ON equipment_catalogs (subject_id);
CREATE INDEX ix_equipment_catalogs_owner ON equipment_catalogs (owner_school_id);

