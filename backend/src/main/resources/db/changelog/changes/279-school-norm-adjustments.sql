-- Thay mô hình đề nghị 154 (standard_adjustment_rules / standard_adjustments): menu ẩn, bảng giữ.
CREATE TABLE school_norm_adjustments (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id            BIGINT NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    school_year_id       BIGINT NOT NULL REFERENCES school_years (id) ON DELETE RESTRICT,
    campus_id            BIGINT REFERENCES campuses (id) ON DELETE CASCADE,
    norm_id              BIGINT REFERENCES equipment_norms (id) ON DELETE SET NULL,
    norm_code            VARCHAR(64) NOT NULL,
    catalog_id           BIGINT REFERENCES equipment_catalogs (id) ON DELETE SET NULL,
    kind                 VARCHAR(20) NOT NULL,
    status               VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    chosen               BOOLEAN,
    outside_need         INTEGER,
    substitute_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    reason               VARCHAR(1000) NOT NULL,
    norm_fingerprint     VARCHAR(64),
    expired_reason       VARCHAR(255),
    expired_at           TIMESTAMP WITH TIME ZONE,
    copied_from_id       BIGINT REFERENCES school_norm_adjustments (id) ON DELETE SET NULL,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    created_by_id        BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_at           TIMESTAMP WITH TIME ZONE,
    updated_by_id        BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_school_norm_adjustments_kind CHECK (kind IN ('REDUCE', 'SUBSTITUTE', 'SHARED', 'CHOOSE_IN_GROUP', 'OUTSIDE')),
    CONSTRAINT ck_school_norm_adjustments_status CHECK (status IN ('ACTIVE', 'PENDING_RECONFIRM', 'EXPIRED')),
    CONSTRAINT ck_school_norm_adjustments_outside CHECK (kind <> 'OUTSIDE' OR outside_need >= 1)
);
CREATE UNIQUE INDEX uq_school_norm_adjustments_live ON school_norm_adjustments (school_year_id, COALESCE(campus_id, 0), norm_id)
    WHERE status <> 'EXPIRED';
CREATE INDEX ix_school_norm_adjustments_school ON school_norm_adjustments (school_id, school_year_id);
CREATE INDEX ix_school_norm_adjustments_norm ON school_norm_adjustments (norm_id);

-- Lưu vết: mỗi lần lưu / bỏ / xác nhận lại / hết hiệu lực / chép sang năm mới.
CREATE TABLE school_norm_adjustment_events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    adjustment_id  BIGINT REFERENCES school_norm_adjustments (id) ON DELETE SET NULL,
    school_id      BIGINT NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    school_year_id BIGINT NOT NULL REFERENCES school_years (id) ON DELETE RESTRICT,
    campus_id      BIGINT REFERENCES campuses (id) ON DELETE SET NULL,
    norm_id        BIGINT REFERENCES equipment_norms (id) ON DELETE SET NULL,
    norm_code      VARCHAR(64),
    action         VARCHAR(20) NOT NULL,
    kind           VARCHAR(20),
    detail         VARCHAR(500),
    reason         VARCHAR(1000),
    actor_id       BIGINT REFERENCES users (id) ON DELETE SET NULL,
    actor_name     VARCHAR(150),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT ck_school_norm_adjustment_events_action CHECK (action IN ('SAVE', 'REMOVE', 'RECONFIRM', 'EXPIRE', 'COPY'))
);
CREATE INDEX ix_school_norm_adjustment_events_school ON school_norm_adjustment_events (school_id, school_year_id, norm_id);

