-- nhập từ tệp hay xoá một dòng; đọc thẳng từ dữ liệu thì không có gì để lệch. Hai người lưu cùng lúc
-- vẫn được unique (school_id, code) của từng bảng chặn.
--
-- Trường chưa khai thì máy chủ dùng mặc định theo "Tùy chỉnh mã danh mục tự động" của bản Jmix
-- (phòng PH0001, cán bộ CB0001; khối nhà NHA-01, cơ sở CS01) — xem SchoolCodeService.

--changeset qltb:089-school-code-rules
CREATE TABLE school_code_rules (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id      BIGINT      NOT NULL REFERENCES schools (id) ON DELETE CASCADE,
    target         VARCHAR(64) NOT NULL,
    prefix         VARCHAR(20),
    number_length  INTEGER     NOT NULL DEFAULT 2,
    start_number   INTEGER     NOT NULL DEFAULT 1,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE,
    created_by_id  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_school_code_rules UNIQUE (school_id, target),
    CONSTRAINT ck_school_code_rules_target CHECK (target IN ('rooms', 'buildings', 'campuses', 'staff')),
    CONSTRAINT ck_school_code_rules_length CHECK (number_length BETWEEN 1 AND 6),
    CONSTRAINT ck_school_code_rules_start CHECK (start_number >= 0)
);

