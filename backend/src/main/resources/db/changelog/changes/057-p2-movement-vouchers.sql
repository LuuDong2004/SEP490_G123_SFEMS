-- ---------------------------------------------------------------- 1. Cấp phát - điều chuyển nội bộ - thu hồi
--
-- Ba việc cùng một khuôn: đổi PHÒNG và NGƯỜI GIỮ của tài sản trong một trường.
--   ALLOCATE  từ kho về phòng (Trong kho → Đang sử dụng)
--   RELOCATE  từ phòng này sang phòng khác
--   RECALL    thu hồi về kho (Đang sử dụng → Trong kho)
CREATE TABLE equipment_allocations (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id         BIGINT       NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    code              VARCHAR(32),
    kind              VARCHAR(20)  NOT NULL,
    allocation_date   DATE         NOT NULL,
    room_id           BIGINT REFERENCES rooms (id) ON DELETE RESTRICT,
    receiver_id       BIGINT REFERENCES staff (id) ON DELETE RESTRICT,
    purpose           VARCHAR(255),
    status            VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    approval_step     VARCHAR(20),
    submitted_at      TIMESTAMP WITH TIME ZONE,
    submitted_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    completed_at      TIMESTAMP WITH TIME ZONE,
    completed_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    cancel_reason     VARCHAR(500),
    reject_reason     VARCHAR(500),
    return_note       VARCHAR(500),
    note              VARCHAR(500),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE,
    created_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_equipment_allocations_school_code UNIQUE (school_id, code)
);
CREATE INDEX ix_equipment_allocations_school ON equipment_allocations (school_id, status);

CREATE TABLE equipment_allocation_lines (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    allocation_id   BIGINT  NOT NULL REFERENCES equipment_allocations (id) ON DELETE CASCADE,
    line_no         INTEGER NOT NULL,
    equipment_id    BIGINT  NOT NULL REFERENCES equipment (id) ON DELETE RESTRICT,
    note            VARCHAR(255)
);
CREATE INDEX ix_equipment_allocation_lines_equipment ON equipment_allocation_lines (equipment_id);

-- ---------------------------------------------------------------- 2. Điều chuyển giữa hai trường
CREATE TABLE equipment_transfers (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id         BIGINT       NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    target_school_id  BIGINT       NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    code              VARCHAR(32),
    transfer_date     DATE         NOT NULL,
    reason            VARCHAR(500),
    decision_no       VARCHAR(100),
    received_room_id  BIGINT REFERENCES rooms (id) ON DELETE RESTRICT,
    status            VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    approval_step     VARCHAR(20),
    submitted_at      TIMESTAMP WITH TIME ZONE,
    submitted_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    completed_at      TIMESTAMP WITH TIME ZONE,
    completed_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    cancel_reason     VARCHAR(500),
    reject_reason     VARCHAR(500),
    return_note       VARCHAR(500),
    note              VARCHAR(500),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE,
    created_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_equipment_transfers_school_code UNIQUE (school_id, code),
    CONSTRAINT ck_equipment_transfers_two_schools CHECK (school_id <> target_school_id)
);
CREATE INDEX ix_equipment_transfers_school ON equipment_transfers (school_id, status);
CREATE INDEX ix_equipment_transfers_target ON equipment_transfers (target_school_id, status);

CREATE TABLE equipment_transfer_lines (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id     BIGINT  NOT NULL REFERENCES equipment_transfers (id) ON DELETE CASCADE,
    line_no         INTEGER NOT NULL,
    equipment_id    BIGINT  NOT NULL REFERENCES equipment (id) ON DELETE RESTRICT,
    condition       VARCHAR(20),
    note            VARCHAR(255)
);
CREATE INDEX ix_equipment_transfer_lines_equipment ON equipment_transfer_lines (equipment_id);

-- ---------------------------------------------------------------- 3. Mượn - trả
CREATE TABLE equipment_loans (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id         BIGINT       NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    code              VARCHAR(32),
    borrower_id       BIGINT       NOT NULL REFERENCES staff (id) ON DELETE RESTRICT,
    loan_date         DATE         NOT NULL,
    due_date          DATE         NOT NULL,
    purpose           VARCHAR(255),
    returned_date     DATE,
    status            VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    approval_step     VARCHAR(20),
    submitted_at      TIMESTAMP WITH TIME ZONE,
    submitted_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    completed_at      TIMESTAMP WITH TIME ZONE,
    completed_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    cancel_reason     VARCHAR(500),
    reject_reason     VARCHAR(500),
    return_note       VARCHAR(500),
    note              VARCHAR(500),
    overdue_notified_at TIMESTAMP WITH TIME ZONE,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE,
    created_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_equipment_loans_school_code UNIQUE (school_id, code),
    CONSTRAINT ck_equipment_loans_dates CHECK (due_date >= loan_date)
);
CREATE INDEX ix_equipment_loans_school ON equipment_loans (school_id, status);
CREATE INDEX ix_equipment_loans_due ON equipment_loans (status, due_date);

CREATE TABLE equipment_loan_lines (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id           BIGINT  NOT NULL REFERENCES equipment_loans (id) ON DELETE CASCADE,
    line_no           INTEGER NOT NULL,
    equipment_id      BIGINT  NOT NULL REFERENCES equipment (id) ON DELETE RESTRICT,
    status_before     VARCHAR(30),
    returned_date     DATE,
    return_outcome    VARCHAR(20),
    return_note       VARCHAR(255),
    note              VARCHAR(255)
);
CREATE INDEX ix_equipment_loan_lines_equipment ON equipment_loan_lines (equipment_id);

-- ---------------------------------------------------------------- 4. Quyền
INSERT INTO permissions (code, name, description, system_permission)
SELECT r.resource || ':' || a.action,
       a.verb || ' ' || r.label,
       a.description,
       TRUE
FROM (VALUES
    ('equipment_allocations', 'phiếu cấp phát'),
    ('equipment_transfers',   'phiếu điều chuyển'),
    ('equipment_loans',       'phiếu mượn - trả')
) AS r(resource, label)
CROSS JOIN (VALUES
    ('read',    'Xem',   'Xem danh sách và chi tiết'),
    ('write',   'Lập',   'Lập, sửa phiếu nháp, trình duyệt, hoàn tất'),
    ('delete',  'Xoá',   'Xoá phiếu nháp chưa từng trình'),
    ('export',  'Xuất',  'Xuất dữ liệu ra tệp (PDF, Excel hoặc CSV)'),
    ('approve', 'Duyệt', 'Duyệt, trả lại, từ chối phiếu')
) AS a(action, verb, description)
WHERE NOT EXISTS (SELECT 1 FROM permissions p WHERE p.code = r.resource || ':' || a.action);

-- Ai được gì: cán bộ thiết bị lập, lãnh đạo trường duyệt; UBND và Sở xem, và
-- DUYỆT điều chuyển (việc liên đơn vị là việc của cơ quan quản lý).
WITH grant_map(role_code, pattern) AS (VALUES
    ('ADMIN', 'equipment_allocations:%'), ('ADMIN', 'equipment_transfers:%'), ('ADMIN', 'equipment_loans:%'),
    ('SCHOOL_STAFF', 'equipment_allocations:read'), ('SCHOOL_STAFF', 'equipment_allocations:write'),
    ('SCHOOL_STAFF', 'equipment_allocations:delete'), ('SCHOOL_STAFF', 'equipment_allocations:export'),
    ('SCHOOL_STAFF', 'equipment_transfers:read'), ('SCHOOL_STAFF', 'equipment_transfers:write'),
    ('SCHOOL_STAFF', 'equipment_transfers:delete'), ('SCHOOL_STAFF', 'equipment_transfers:export'),
    ('SCHOOL_STAFF', 'equipment_loans:read'), ('SCHOOL_STAFF', 'equipment_loans:write'),
    ('SCHOOL_STAFF', 'equipment_loans:delete'), ('SCHOOL_STAFF', 'equipment_loans:export'),
    ('SCHOOL_LEADER', 'equipment_allocations:read'), ('SCHOOL_LEADER', 'equipment_allocations:export'),
    ('SCHOOL_LEADER', 'equipment_allocations:approve'),
    ('SCHOOL_LEADER', 'equipment_transfers:read'), ('SCHOOL_LEADER', 'equipment_transfers:export'),
    ('SCHOOL_LEADER', 'equipment_transfers:approve'),
    ('SCHOOL_LEADER', 'equipment_loans:read'), ('SCHOOL_LEADER', 'equipment_loans:export'),
    ('UBND_LEADER', 'equipment_allocations:read'), ('UBND_LEADER', 'equipment_transfers:read'),
    ('UBND_LEADER', 'equipment_transfers:export'), ('UBND_LEADER', 'equipment_transfers:approve'),
    ('UBND_LEADER', 'equipment_loans:read'),
    ('UBND_SPECIALIST', 'equipment_allocations:read'), ('UBND_SPECIALIST', 'equipment_transfers:read'),
    ('UBND_SPECIALIST', 'equipment_transfers:export'), ('UBND_SPECIALIST', 'equipment_loans:read'),
    ('SO_LEADER', 'equipment_allocations:read'), ('SO_LEADER', 'equipment_allocations:export'),
    ('SO_LEADER', 'equipment_transfers:read'), ('SO_LEADER', 'equipment_transfers:export'),
    ('SO_LEADER', 'equipment_transfers:approve'),
    ('SO_LEADER', 'equipment_loans:read'), ('SO_LEADER', 'equipment_loans:export'),
    ('SO_SPECIALIST', 'equipment_allocations:read'), ('SO_SPECIALIST', 'equipment_allocations:export'),
    ('SO_SPECIALIST', 'equipment_transfers:read'), ('SO_SPECIALIST', 'equipment_transfers:export'),
    ('SO_SPECIALIST', 'equipment_loans:read'), ('SO_SPECIALIST', 'equipment_loans:export')
)
INSERT INTO role_permissions (role_id, permission_id)
SELECT DISTINCT r.id, p.id
FROM grant_map g
JOIN roles r ON r.code = g.role_code
JOIN permissions p ON p.code LIKE g.pattern
WHERE NOT EXISTS (SELECT 1 FROM role_permissions rp WHERE rp.role_id = r.id AND rp.permission_id = p.id);

-- ---------------------------------------------------------------- 5. Phạm vi dữ liệu
--
-- Như mọi bảng thuộc trường (055). Riêng phiếu điều chuyển: trường NHẬN cũng
-- phải đọc được phiếu — họ là người xác nhận đã nhận hàng.
WITH res(resource) AS (VALUES ('equipment_allocations'), ('equipment_transfers'), ('equipment_loans')),
plan(role_code, action, name, scope) AS (VALUES
    ('ADMIN', 'read', 'Mọi trường', '{"all": []}'),
    ('ADMIN', 'write', 'Mọi trường', '{"all": []}'),
    ('ADMIN', 'delete', 'Mọi trường', '{"all": []}'),
    ('SO_LEADER', 'read', 'Sở xem mọi trường', '{"all": []}'),
    ('SO_SPECIALIST', 'read', 'Sở xem mọi trường', '{"all": []}'),
    ('UBND_LEADER', 'read', 'UBND xem trường trên địa bàn',
     '{"field": "school.id", "op": "in", "value": {"ctx": "user.managedSchoolIds"}}'),
    ('UBND_SPECIALIST', 'read', 'UBND xem trường trên địa bàn',
     '{"field": "school.id", "op": "in", "value": {"ctx": "user.managedSchoolIds"}}'),
    ('SCHOOL_LEADER', 'read', 'Chỉ trường của mình',
     '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'),
    ('SCHOOL_STAFF', 'read', 'Chỉ trường của mình',
     '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'),
    ('SCHOOL_STAFF', 'write', 'Chỉ trường của mình',
     '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'),
    ('SCHOOL_STAFF', 'delete', 'Chỉ trường của mình',
     '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'))
INSERT INTO row_level_policy (kind, role_id, resource, action, name, description, scope, created_at)
SELECT 'SCOPE', r.id, res.resource, plan.action, plan.name, plan.name,
       CASE
           WHEN res.resource = 'equipment_transfers' AND plan.action = 'read' AND plan.role_code LIKE 'SCHOOL_%'
               THEN '{"any": [{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}},
                              {"field": "targetSchool.id", "op": "eq", "value": {"ctx": "user.schoolId"}}]}'
           WHEN res.resource = 'equipment_transfers' AND plan.action = 'read' AND plan.role_code LIKE 'UBND_%'
               THEN '{"any": [{"field": "school.id", "op": "in", "value": {"ctx": "user.managedSchoolIds"}},
                              {"field": "targetSchool.id", "op": "in", "value": {"ctx": "user.managedSchoolIds"}}]}'
           ELSE plan.scope
       END::jsonb,
       now()
FROM plan
JOIN roles r ON r.code = plan.role_code
CROSS JOIN res
WHERE NOT EXISTS (
    SELECT 1 FROM row_level_policy p
    WHERE p.role_id = r.id AND p.resource = res.resource AND p.action = plan.action);
