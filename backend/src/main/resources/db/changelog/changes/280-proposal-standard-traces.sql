CREATE TABLE proposal_standard_traces (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposal_id       BIGINT NOT NULL REFERENCES purchase_proposals (id) ON DELETE CASCADE,
    school_id         BIGINT NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    school_year_id    BIGINT NOT NULL REFERENCES school_years (id) ON DELETE RESTRICT,
    catalog_id        BIGINT NOT NULL REFERENCES equipment_catalogs (id) ON DELETE RESTRICT,
    campus_id         BIGINT REFERENCES campuses (id) ON DELETE SET NULL,
    campus_name       VARCHAR(255),
    norm_id           BIGINT REFERENCES equipment_norms (id) ON DELETE SET NULL,
    norm_code         VARCHAR(64),
    quantity          INTEGER NOT NULL,
    required_tt       INTEGER,
    required_adjusted INTEGER,
    current_qty       INTEGER,
    adjust_kind       VARCHAR(20),
    adjust_reason     VARCHAR(1000),
    basis_text        VARCHAR(1000),
    outside_standard  BOOLEAN NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX ix_proposal_standard_traces_proposal ON proposal_standard_traces (proposal_id);
CREATE INDEX ix_proposal_standard_traces_school ON proposal_standard_traces (school_id, school_year_id);

