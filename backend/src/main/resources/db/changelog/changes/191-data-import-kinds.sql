CREATE TABLE data_import_snapshots (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id   BIGINT      NOT NULL REFERENCES data_import_batches (id) ON DELETE CASCADE,
    resource   VARCHAR(40) NOT NULL,
    record_id  BIGINT      NOT NULL,
    action     VARCHAR(20) NOT NULL,
    before     JSONB       NOT NULL,
    CONSTRAINT ck_data_import_snapshots_action CHECK (action IN ('UPDATE', 'DEACTIVATE'))
);
CREATE INDEX ix_data_import_snapshots_batch ON data_import_snapshots (batch_id);

COMMENT ON TABLE data_import_snapshots IS 'Giá trị TRƯỚC khi lô danh mục sửa / ngừng một bản ghi — để hoàn tác';
