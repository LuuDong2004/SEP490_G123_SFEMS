--changeset qltb:205-inventory-facility-lines
-- Kiểm kê hạng mục CSVC (QLTB-654, 655): phiếu kiểm kê kiểm thêm khối nhà và phòng / hạng mục trong phạm vi của nó. Mỗi
-- dòng chụp kết cấu và hiện trạng trên hồ sơ lúc lập (`*_before`), tổ kiểm kê ghi cái thấy (`*_found`). Áp dụng kết quả
-- (phiếu đã duyệt) ghi phần thấy vào hồ sơ CSVC — qua luật xác nhận 202: cán bộ áp thì "Chờ xác nhận".
CREATE TABLE inventory_facility_lines (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id       BIGINT      NOT NULL REFERENCES inventory_sessions (id) ON DELETE CASCADE,
    room_id          BIGINT      REFERENCES rooms (id) ON DELETE CASCADE,
    building_id      BIGINT      REFERENCES buildings (id) ON DELETE CASCADE,
    structure_before VARCHAR(20),
    condition_before VARCHAR(30),
    structure_found  VARCHAR(20),
    condition_found  VARCHAR(30),
    checked          BOOLEAN     NOT NULL DEFAULT FALSE,
    note             VARCHAR(500),
    applied_at       TIMESTAMP WITH TIME ZONE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_inventory_facility_lines_target CHECK ((room_id IS NULL) <> (building_id IS NULL)),
    CONSTRAINT uq_inventory_facility_lines_room UNIQUE (session_id, room_id),
    CONSTRAINT uq_inventory_facility_lines_building UNIQUE (session_id, building_id)
);
CREATE INDEX idx_inventory_facility_lines_room ON inventory_facility_lines (room_id) WHERE room_id IS NOT NULL;
CREATE INDEX idx_inventory_facility_lines_building ON inventory_facility_lines (building_id) WHERE building_id IS NOT NULL;
