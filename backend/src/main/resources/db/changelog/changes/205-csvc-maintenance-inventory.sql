-- Kế hoạch bảo trì cho CÔNG TRÌNH (QLTB-650): ngoài thiết bị, kế hoạch nhắm thẳng một khối nhà hoặc một phòng / hạng mục
-- CSVC (mái, sân, hàng rào, nhà vệ sinh). `target` = EQUIPMENT (như cũ: tài sản hoặc cả phòng) | FACILITY (khối nhà
-- hoặc phòng / hạng mục, không kèm tài sản). Lãnh đạo DUYỆT kế hoạch (QLTB-653): cán bộ lập / sửa → chờ duyệt; lãnh đạo
-- (maintenance_plans:approve) lập / sửa thì duyệt luôn. Chỉ kế hoạch đã duyệt và đang áp dụng mới được nhắc. Kế hoạch
-- đã có trước là thiết bị, đã duyệt (không dồn việc cho lãnh đạo).
ALTER TABLE maintenance_plans
    ADD COLUMN target          VARCHAR(20) NOT NULL DEFAULT 'EQUIPMENT'
        CONSTRAINT ck_maintenance_plans_target CHECK (target IN ('EQUIPMENT', 'FACILITY')),
    ADD COLUMN building_id     BIGINT
        CONSTRAINT fk_maintenance_plans_building REFERENCES buildings (id) ON DELETE CASCADE,
    ADD COLUMN approval_status VARCHAR(20) NOT NULL DEFAULT 'APPROVED'
        CONSTRAINT ck_maintenance_plans_approval CHECK (approval_status IN ('PENDING', 'APPROVED', 'RETURNED')),
    ADD COLUMN approved_by_id  BIGINT
        CONSTRAINT fk_maintenance_plans_approved_by REFERENCES users (id) ON DELETE SET NULL,
    ADD COLUMN approved_at     TIMESTAMP WITH TIME ZONE,
    ADD COLUMN approval_note   VARCHAR(500);
ALTER TABLE maintenance_plans ADD CONSTRAINT ck_maintenance_plans_facility
    CHECK (target <> 'FACILITY' OR building_id IS NOT NULL OR room_id IS NOT NULL);
CREATE INDEX idx_maintenance_plans_building ON maintenance_plans (building_id) WHERE building_id IS NOT NULL;
CREATE INDEX idx_maintenance_plans_approval_open ON maintenance_plans (school_id) WHERE approval_status <> 'APPROVED';
