CREATE TABLE school_types (
    id bigint NOT NULL,
    code character varying(64) NOT NULL,
    name character varying(255) NOT NULL,
    short_name character varying(64),
    sort_order integer,
    active boolean DEFAULT true NOT NULL,
    note character varying(500),
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone,
    created_by_id bigint,
    updated_by_id bigint
);

ALTER TABLE school_types ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME school_types_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY school_types
    ADD CONSTRAINT pk_school_types PRIMARY KEY (id);

ALTER TABLE ONLY school_types
    ADD CONSTRAINT uq_school_types_code UNIQUE (code);

CREATE INDEX idx_school_types_sort ON school_types USING btree (sort_order, name);

