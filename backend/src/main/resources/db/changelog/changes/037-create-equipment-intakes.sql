-- Phiếu nhập. Số phiếu (code) RỖNG khi còn là nháp và chỉ được cấp lúc xác
-- nhận, nên khoá duy nhất để NULL ở chế độ mặc định (NULL khác NULL): nhiều
-- phiếu nháp cùng lúc là chuyện bình thường, hai phiếu cùng SỐ thì không.
CREATE TABLE equipment_intakes (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id              BIGINT       NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    code                   VARCHAR(32),
    intake_date            DATE         NOT NULL,
    document_no            VARCHAR(100),
    document_date          DATE,
    supplier               VARCHAR(255),
    funding_source         VARCHAR(30),
    origin_source_id       BIGINT REFERENCES origin_sources (id) ON DELETE RESTRICT,
    acquisition_method_id  BIGINT REFERENCES acquisition_methods (id) ON DELETE RESTRICT,
    warranty_months        INTEGER,
    note                   VARCHAR(500),
    status                 VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    confirmed_at           TIMESTAMP WITH TIME ZONE,
    confirmed_by_id        BIGINT REFERENCES users (id) ON DELETE SET NULL,
    cancel_reason          VARCHAR(255),
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at             TIMESTAMP WITH TIME ZONE,
    created_by_id          BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id          BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_equipment_intakes_school_code UNIQUE (school_id, code),
    CONSTRAINT ck_equipment_intakes_warranty CHECK (warranty_months IS NULL OR warranty_months >= 0),
    -- Phiếu đã xác nhận thì PHẢI có số và thời điểm xác nhận. Đây là nửa còn
    -- lại của luật "xác nhận là thời điểm ghi tăng": không có đường nào để một
    -- phiếu vừa ghi tăng tài sản vừa không mang số chứng từ nào.
    CONSTRAINT ck_equipment_intakes_confirmed CHECK (
        status <> 'CONFIRMED' OR (code IS NOT NULL AND confirmed_at IS NOT NULL))
);
CREATE INDEX ix_equipment_intakes_school ON equipment_intakes (school_id);
CREATE INDEX ix_equipment_intakes_status ON equipment_intakes (status);
CREATE INDEX ix_equipment_intakes_date ON equipment_intakes (intake_date);

-- Dòng phiếu. CASCADE chứ không RESTRICT như mọi khoá ngoại khác ở nền này:
-- dòng là THÀNH PHẦN của phiếu, không sống ngoài nó, nên xoá phiếu nháp phải
-- xoá luôn các dòng. Phiếu đã xác nhận thì không xoá được — việc đó do tài sản
-- trỏ ngược vào dòng giữ lại, ở khoá ngoại dưới.
CREATE TABLE equipment_intake_lines (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intake_id            BIGINT       NOT NULL REFERENCES equipment_intakes (id) ON DELETE CASCADE,
    line_no              INTEGER      NOT NULL,
    catalog_id           BIGINT       NOT NULL REFERENCES equipment_catalogs (id) ON DELETE RESTRICT,
    name                 VARCHAR(255) NOT NULL,
    physical_or_digital  VARCHAR(20)  NOT NULL DEFAULT 'PHYSICAL',
    asset_category       VARCHAR(20),
    document_quantity    INTEGER      NOT NULL,
    received_quantity    INTEGER      NOT NULL,
    variance_reason      VARCHAR(255),
    unit_price           NUMERIC(18, 2),
    room_id              BIGINT REFERENCES rooms (id) ON DELETE RESTRICT,
    generated_count      INTEGER      NOT NULL DEFAULT 0,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at           TIMESTAMP WITH TIME ZONE,
    created_by_id        BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id        BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_equipment_intake_lines_no UNIQUE (intake_id, line_no),
    CONSTRAINT ck_equipment_intake_lines_doc_qty CHECK (document_quantity >= 1),
    CONSTRAINT ck_equipment_intake_lines_recv_qty CHECK (received_quantity >= 0),
    CONSTRAINT ck_equipment_intake_lines_price CHECK (unit_price IS NULL OR unit_price >= 0),
    -- Lệch số lượng thì phải có lý do. Luật này cũng nằm ở service để câu báo
    -- lỗi gọi đúng tên dòng; ở đây là để không cửa nào khác ghi được dữ liệu
    -- mà màn hình sẽ không giải thích nổi.
    CONSTRAINT ck_equipment_intake_lines_variance CHECK (
        document_quantity = received_quantity OR variance_reason IS NOT NULL)
);
CREATE INDEX ix_equipment_intake_lines_intake ON equipment_intake_lines (intake_id);
CREATE INDEX ix_equipment_intake_lines_catalog ON equipment_intake_lines (catalog_id);

-- Truy ngược tài sản về phiếu đã sinh ra nó. RESTRICT: mất dòng phiếu là mất
-- nguồn gốc của tài sản.
ALTER TABLE equipment
    ADD COLUMN intake_line_id BIGINT REFERENCES equipment_intake_lines (id) ON DELETE RESTRICT;
CREATE INDEX ix_equipment_intake_line ON equipment (intake_line_id);

-- Tồn kho của loại quản lý theo số lượng. NULLS NOT DISTINCT là phần quan
-- trọng: room_id rỗng nghĩa là KHO — một vị trí thật — nên hai lần nhập vào kho
-- phải cộng vào cùng một dòng. Với chế độ mặc định của Postgres, NULL khác
-- NULL, và mỗi lần nhập sẽ đẻ thêm một dòng tồn.
CREATE TABLE equipment_stock (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id      BIGINT  NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    catalog_id     BIGINT  NOT NULL REFERENCES equipment_catalogs (id) ON DELETE RESTRICT,
    room_id        BIGINT REFERENCES rooms (id) ON DELETE RESTRICT,
    quantity       INTEGER NOT NULL DEFAULT 0,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE,
    created_by_id  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_equipment_stock_place UNIQUE NULLS NOT DISTINCT (school_id, catalog_id, room_id),
    CONSTRAINT ck_equipment_stock_quantity CHECK (quantity >= 0)
);
CREATE INDEX ix_equipment_stock_school ON equipment_stock (school_id);

-- Bộ đếm số phiếu: một dòng cho mỗi (trường, NK-<năm>). Không có entity — chỉ
-- IntakeNumberService đụng tới, bằng một lệnh upsert, như bộ đếm mã thiết bị.
CREATE TABLE document_number_sequences (
    school_id       BIGINT      NOT NULL REFERENCES schools (id) ON DELETE CASCADE,
    prefix          VARCHAR(20) NOT NULL,
    current_number  INTEGER     NOT NULL,
    CONSTRAINT pk_document_number_sequences PRIMARY KEY (school_id, prefix)
);

