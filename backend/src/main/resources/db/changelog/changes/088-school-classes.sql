-- nhiệm, phòng học, sĩ số. Mỗi năm học một bộ lớp, nên tên lớp chỉ duy nhất trong (trường, năm học):
-- "6A1" năm nay và "6A1" năm sau là hai lớp khác nhau.
--
-- Quyền và phạm vi dòng KHÔNG viết tay: chép đúng những gì từng vai trò đang có trên `rooms`
-- (mã quyền đổi tiền tố, chính sách đổi tên resource). Lớp học và phòng cùng là "cơ sở của
-- trường" và cùng một người quản — viết lại tay là mời hai bộ lệch nhau, và cấp mã quyền mà quên
-- chính sách là kiểu hỏng khó chẩn đoán nhất (xem CLAUDE.md, mục 072).

