CREATE TABLE school_classes (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id            BIGINT       NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    code                 VARCHAR(64)  NOT NULL,
    name                 VARCHAR(255) NOT NULL,
    sort_order           INTEGER,
    active               BOOLEAN      NOT NULL DEFAULT TRUE,
    note                 VARCHAR(500),
    grade_id             BIGINT       NOT NULL REFERENCES grades (id) ON DELETE RESTRICT,
    school_year_id       BIGINT       NOT NULL REFERENCES school_years (id) ON DELETE RESTRICT,
    homeroom_teacher_id  BIGINT REFERENCES staff (id) ON DELETE SET NULL,
    room_id              BIGINT REFERENCES rooms (id) ON DELETE SET NULL,
    student_count        INTEGER,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at           TIMESTAMP WITH TIME ZONE,
    created_by_id        BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id        BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_school_classes_year_code UNIQUE (school_id, school_year_id, code),
    CONSTRAINT ck_school_classes_students CHECK (student_count IS NULL OR student_count >= 0)
);
CREATE INDEX ix_school_classes_school ON school_classes (school_id);
CREATE INDEX ix_school_classes_year ON school_classes (school_year_id);

