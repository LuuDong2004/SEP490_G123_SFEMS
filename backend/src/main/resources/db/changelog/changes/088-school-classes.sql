-- class_count = 24 seed ở 061), sĩ số 40–44.
INSERT INTO school_classes (school_id, code, name, sort_order, grade_id, school_year_id, student_count, created_at)
SELECT s.id,
       g.n || 'A' || k.i,
       'Lớp ' || g.n || 'A' || k.i,
       g.n * 100 + k.i,
       gr.id,
       y.id,
       40 + ((g.n + k.i) % 5),
       now()
FROM schools s
CROSS JOIN (VALUES (6), (7), (8), (9)) AS g(n)
CROSS JOIN generate_series(1, 6) AS k(i)
JOIN grades gr ON gr.code = 'LOP_' || g.n
JOIN school_years y ON y.is_current
WHERE s.code = 'THCSBINHANQ2';
