--comment Danh sách học sinh từng em của trường (họ tên, ngày sinh, giới tính, lớp). Sĩ số của lớp có học sinh tự đếm từ danh sách này. Dữ liệu cá nhân của trẻ vị thành niên: chỉ vai loại trường mang quyền, Sở và quản trị viên không xem (Sở vẫn thấy sĩ số qua lớp).

-- 1. Bảng. Năm học suy ra từ lớp (mỗi năm học một bộ lớp), nên không có cột năm học riêng. Mã học sinh duy nhất
--    trong một lớp. `sort_order` có vì học sinh dùng chung khuôn danh mục của trường (CatalogEntity) — thứ tự nhập.
--    Index theo lớp là chính ràng buộc duy nhất (class_id đứng đầu).
CREATE TABLE students (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id      BIGINT       NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    class_id       BIGINT       NOT NULL REFERENCES school_classes (id) ON DELETE RESTRICT,
    code           VARCHAR(64)  NOT NULL,
    full_name      VARCHAR(255) NOT NULL,
    birth_date     DATE,
    gender         VARCHAR(16),
    sort_order     INTEGER,
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    note           VARCHAR(500),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE,
    created_by_id  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_students_class_code UNIQUE (class_id, code),
    CONSTRAINT ck_students_gender CHECK (gender IS NULL OR gender IN ('MALE', 'FEMALE'))
);
CREATE INDEX ix_students_school ON students (school_id);

-- 2. Lớp CSDL (docs/kien-truc/03 "Lớp CSDL"): nhóm "chặt" như school_classes ở 231 — đọc, ghi trường mình.
ALTER TABLE students ENABLE ROW LEVEL SECURITY;
ALTER TABLE students FORCE ROW LEVEL SECURITY;
CREATE POLICY rls_school ON students FOR ALL
    USING (NOT (SELECT public.rls_restricted()) OR school_id = ANY ((SELECT public.rls_school_ids())::bigint[]))
    WITH CHECK (NOT (SELECT public.rls_restricted()) OR school_id = ANY ((SELECT public.rls_school_ids())::bigint[]));

-- 3. Quyền.
INSERT INTO permissions (code, name, description, system_permission, scope) VALUES
    ('students:read',   'Xem học sinh',  'Xem danh sách học sinh của trường', TRUE, 'ORGANIZATION'),
    ('students:write',  'Sửa học sinh',  'Thêm, sửa học sinh, chuyển lớp', TRUE, 'ORGANIZATION'),
    ('students:delete', 'Xoá học sinh',  'Xoá hồ sơ học sinh', TRUE, 'ORGANIZATION'),
    ('students:export', 'Xuất học sinh', 'Xuất danh sách học sinh', TRUE, 'ORGANIZATION');

-- 4. Cấp quyền: CHỈ vai loại trường, chép đúng những gì vai đó đang có trên school_classes (lớp và học sinh cùng
--    một người quản). Vai Sở, vai quản trị không có — kể cả quyền xem.
INSERT INTO role_permissions (role_id, permission_id)
SELECT rp.role_id, target.id
FROM role_permissions rp
JOIN roles r ON r.id = rp.role_id AND r.role_type = 'SCHOOL'
JOIN permissions src ON src.id = rp.permission_id AND src.code LIKE 'school_classes:%'
JOIN permissions target ON target.code = 'students:' || split_part(src.code, ':', 2);

-- 5. Phạm vi dòng của school_classes, chép sang students cho đúng các vai loại trường (cùng hành động, cùng điều kiện).
INSERT INTO row_level_policy (kind, role_id, resource, action, name, policy_group, description, scope, check_scope, enabled, created_at)
SELECT p.kind, p.role_id, 'students', p.action, p.name, p.policy_group, p.description, p.scope, p.check_scope, p.enabled, now()
FROM row_level_policy p
JOIN roles r ON r.id = p.role_id AND r.role_type = 'SCHOOL'
WHERE p.resource = 'school_classes';

-- 6. CSDL giữ luật quyền học sinh: chỉ vai loại trường mang được (PermissionGrants theo cổng — PortalRoutes mở
--    /api/students ở riêng cổng trường). Hàm như 290, thêm một nhánh cho students.
CREATE OR REPLACE FUNCTION role_permission_fits() RETURNS trigger LANGUAGE plpgsql AS $fn$
DECLARE
    rt TEXT;
    ps TEXT;
    pc TEXT;
BEGIN
    SELECT role_type INTO rt FROM roles WHERE id = NEW.role_id;
    SELECT scope, code INTO ps, pc FROM permissions WHERE id = NEW.permission_id;
    IF rt <> 'SYSTEM' AND ps = 'SYSTEM' THEN
        RAISE EXCEPTION 'Quyền phạm vi % không gán được cho vai loại %', ps, rt USING ERRCODE = 'check_violation';
    END IF;
    IF pc = 'school_year_profiles:confirm' AND rt <> 'SCHOOL' THEN
        RAISE EXCEPTION 'Quyền % không gán được cho vai loại %', pc, rt USING ERRCODE = 'check_violation';
    END IF;
    IF split_part(pc, ':', 1) = 'students' AND rt <> 'SCHOOL' THEN
        RAISE EXCEPTION 'Quyền % không gán được cho vai loại %: danh sách học sinh chỉ trường xem', pc, rt
            USING ERRCODE = 'check_violation';
    END IF;
    IF rt = 'SYSTEM' AND split_part(pc, ':', 2) NOT IN ('read', 'export')
       AND split_part(pc, ':', 1) IN ('buildings', 'campuses', 'rooms', 'equipment', 'inventory_sessions',
            'school_classes', 'staff', 'staff_accounts', 'subject_teams', 'data_transfer', 'equipment_intakes',
            'purchase_proposals', 'inventory_campaigns', 'procurement_plans', 'data_imports', 'staff_assignments',
            'school_norm_adjustments', 'school_profile', 'school_year_profiles') THEN
        RAISE EXCEPTION 'Quyền % không gán được cho vai loại %: quản trị viên chỉ xem, xuất dữ liệu nghiệp vụ', pc, rt
            USING ERRCODE = 'check_violation';
    END IF;
    IF rt = 'SYSTEM' AND split_part(pc, ':', 1) = 'school_code_rules' THEN
        RAISE EXCEPTION 'Quyền % không gán được cho vai loại %', pc, rt USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END $fn$;
