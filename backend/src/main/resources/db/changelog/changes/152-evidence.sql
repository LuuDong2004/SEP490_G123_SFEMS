-- Thu thập minh chứng hoạt động hằng năm (QLTB-143). Sở khai DANH MỤC tiêu chí (mã, tên, mô tả, cấp học áp dụng —
-- trống là mọi cấp, bắt buộc hay không); mỗi năm học mỗi trường nộp tệp cho từng tiêu chí; cơ quan quản lý nhận hoặc
-- trả lại từng mục và xem trường nào đủ / thiếu. Danh sách tiêu chí BA bổ sung sau — đây là khung.
CREATE TABLE evidence_criteria (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR(40)   NOT NULL,
    name                VARCHAR(300)  NOT NULL,
    description         VARCHAR(2000),
    education_level_id  BIGINT REFERENCES education_levels (id) ON DELETE RESTRICT,
    required            BOOLEAN       NOT NULL DEFAULT TRUE,
    sort_order          INTEGER       NOT NULL DEFAULT 0,
    active              BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at          TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_evidence_criteria_code UNIQUE (code)
);

CREATE TABLE evidence_submissions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id          BIGINT        NOT NULL REFERENCES schools (id) ON DELETE CASCADE,
    school_year_id     BIGINT        NOT NULL REFERENCES school_years (id) ON DELETE RESTRICT,
    criterion_id       BIGINT        NOT NULL REFERENCES evidence_criteria (id) ON DELETE RESTRICT,
    status             VARCHAR(20)   NOT NULL DEFAULT 'DRAFT',
    note               VARCHAR(1000),
    review_note        VARCHAR(1000),
    submitted_at       TIMESTAMP WITH TIME ZONE,
    submitted_by_name  VARCHAR(150),
    reviewed_at        TIMESTAMP WITH TIME ZONE,
    reviewed_by_name   VARCHAR(150),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at         TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_evidence_submission UNIQUE (school_id, school_year_id, criterion_id),
    CONSTRAINT ck_evidence_submission_status CHECK (status IN ('DRAFT', 'SUBMITTED', 'ACCEPTED', 'RETURNED'))
);
CREATE INDEX ix_evidence_submissions_year ON evidence_submissions (school_year_id, school_id);

