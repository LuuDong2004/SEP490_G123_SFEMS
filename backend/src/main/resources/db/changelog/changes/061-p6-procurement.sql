-- ---------------------------------------------------------------- 1. Quy mô trường
--
-- Định mức "mỗi lớp một bộ" không tính được khi không biết trường có mấy lớp.
ALTER TABLE schools
    ADD COLUMN class_count    INTEGER CHECK (class_count IS NULL OR class_count >= 0),
    ADD COLUMN student_count  INTEGER CHECK (student_count IS NULL OR student_count >= 0);

-- ---------------------------------------------------------------- 2. Đề xuất mua sắm
CREATE TABLE purchase_proposals (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id         BIGINT       NOT NULL REFERENCES schools (id) ON DELETE RESTRICT,
    code              VARCHAR(32),
    proposal_date     DATE         NOT NULL,
    budget_year       INTEGER,
    funding_source    VARCHAR(30),
    reason            VARCHAR(1000),
    status            VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    approval_step     VARCHAR(20),
    submitted_at      TIMESTAMP WITH TIME ZONE,
    submitted_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    completed_at      TIMESTAMP WITH TIME ZONE,
    completed_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    cancel_reason     VARCHAR(500),
    reject_reason     VARCHAR(500),
    return_note       VARCHAR(500),
    note              VARCHAR(500),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE,
    created_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_purchase_proposals_school_code UNIQUE (school_id, code)
);
CREATE INDEX ix_purchase_proposals_school ON purchase_proposals (school_id, status);

CREATE TABLE purchase_proposal_lines (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposal_id         BIGINT       NOT NULL REFERENCES purchase_proposals (id) ON DELETE CASCADE,
    line_no             INTEGER      NOT NULL,
    kind                VARCHAR(20)  NOT NULL DEFAULT 'NEW',
    catalog_id          BIGINT       NOT NULL REFERENCES equipment_catalogs (id) ON DELETE RESTRICT,
    name                VARCHAR(255) NOT NULL,
    specification       VARCHAR(1000),
    unit_name           VARCHAR(50),
    quantity            INTEGER      NOT NULL CHECK (quantity > 0),
    unit_price          NUMERIC(18, 2) CHECK (unit_price IS NULL OR unit_price >= 0),
    priority            INTEGER      NOT NULL DEFAULT 2 CHECK (priority BETWEEN 1 AND 3),
    current_quantity    INTEGER,
    required_quantity   INTEGER,
    note                VARCHAR(255)
);
CREATE INDEX ix_purchase_proposal_lines_proposal ON purchase_proposal_lines (proposal_id);

-- ---------------------------------------------------------------- 3. Kế hoạch mua sắm cấp UBND / Sở
CREATE TABLE procurement_plans (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    managing_body_id  BIGINT       NOT NULL REFERENCES departments_of_education (id) ON DELETE RESTRICT,
    title             VARCHAR(255) NOT NULL,
    budget_year       INTEGER      NOT NULL,
    status            VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    note              VARCHAR(1000),
    approved_at       TIMESTAMP WITH TIME ZONE,
    approved_by_id    BIGINT REFERENCES users (id) ON DELETE SET NULL,
    approval_note     VARCHAR(500),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE,
    created_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id     BIGINT REFERENCES users (id) ON DELETE SET NULL
);
-- Đề xuất đã duyệt được đưa vào (đúng) một kế hoạch; kế hoạch duyệt xong thì đề xuất hoàn tất.
ALTER TABLE purchase_proposals
    ADD COLUMN plan_id BIGINT REFERENCES procurement_plans (id) ON DELETE SET NULL,
    ADD COLUMN intake_id BIGINT REFERENCES equipment_intakes (id) ON DELETE SET NULL;
CREATE INDEX ix_purchase_proposals_plan ON purchase_proposals (plan_id);

-- ---------------------------------------------------------------- 4. Quyền
INSERT INTO permissions (code, name, description, system_permission)
SELECT r.resource || ':' || a.action, a.verb || ' ' || r.label, a.description, TRUE
FROM (VALUES ('purchase_proposals', 'đề xuất mua sắm'), ('procurement_plans', 'kế hoạch mua sắm')) AS r(resource, label)
CROSS JOIN (VALUES
    ('read',    'Xem',   'Xem danh sách và chi tiết'),
    ('write',   'Lập',   'Lập, sửa, trình'),
    ('delete',  'Xoá',   'Xoá bản ghi nháp'),
    ('export',  'Xuất',  'Xuất dữ liệu ra tệp (PDF, Excel hoặc CSV)'),
    ('approve', 'Duyệt', 'Duyệt, trả lại, từ chối')
) AS a(action, verb, description)
WHERE NOT EXISTS (SELECT 1 FROM permissions p WHERE p.code = r.resource || ':' || a.action);

