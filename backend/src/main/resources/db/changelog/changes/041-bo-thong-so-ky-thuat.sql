CREATE TABLE equipment_configs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code character varying(64) NOT NULL,
    name character varying(255) NOT NULL,
    sort_order integer,
    active boolean DEFAULT true NOT NULL,
    note character varying(500),
    description character varying(500),
    is_default boolean DEFAULT false NOT NULL,
    document_no character varying(100),
    document_name character varying(255),
    issue_date date,
    start_school_year_id bigint REFERENCES school_years (id) ON DELETE RESTRICT,
    end_school_year_id bigint REFERENCES school_years (id) ON DELETE RESTRICT,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone,
    created_by_id bigint REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id bigint REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_equipment_configs_code UNIQUE (code)
);

CREATE INDEX idx_equipment_configs_sort ON equipment_configs USING btree (sort_order, name);

-- Phạm vi: bộ dùng cho những loại thiết bị nào. Không dòng nào là dùng cho mọi loại.
CREATE TABLE equipment_config_scope_types (
    config_id bigint NOT NULL REFERENCES equipment_configs (id) ON DELETE CASCADE,
    equipment_type_id bigint NOT NULL REFERENCES equipment_types (id) ON DELETE RESTRICT,
    CONSTRAINT pk_equipment_config_scope_types PRIMARY KEY (config_id, equipment_type_id)
);

-- Định nghĩa từng thông số trong bộ; giá trị theo từng thiết bị lưu ở sổ tài sản, theo mã thông số.
CREATE TABLE equipment_config_attributes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_id bigint NOT NULL REFERENCES equipment_configs (id) ON DELETE CASCADE,
    code character varying(64) NOT NULL,
    name character varying(255) NOT NULL,
    data_type character varying(20) DEFAULT 'TEXT' NOT NULL,
    measure_unit character varying(32),
    required boolean DEFAULT false NOT NULL,
    options text,
    sort_order integer,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone,
    created_by_id bigint REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id bigint REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_equipment_config_attributes_code UNIQUE (config_id, code),
    CONSTRAINT ck_equipment_config_attributes_type
        CHECK (data_type IN ('TEXT', 'INTEGER', 'DECIMAL', 'BOOLEAN', 'DATE', 'ENUM'))
);

