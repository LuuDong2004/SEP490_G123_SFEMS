-- ---------------------------------------------------------------- 1. Nhật ký duyệt
--
-- Mỗi lần một phiếu đổi trạng thái — trình, duyệt, trả lại, từ chối, huỷ, hoàn
-- tất — là MỘT dòng ở đây. Đó là thứ trả lời "ai duyệt, lúc nào, nói gì" trên
-- màn chi tiết phiếu, và là vết mà HSMT mục 3.9.6 đòi cho thao tác phê duyệt.
--
-- Một bảng cho MỌI loại phiếu, khoá bằng (resource, voucher_id) chứ không phải
-- khoá ngoại: bảy loại phiếu với bảy bảng nhật ký gần giống hệt nhau là bảy chỗ
-- để quên một cột. Cái giá là không có khoá ngoại — và vì phiếu đã có dòng nhật
-- ký thì không xoá được (service chặn), nên không có dòng nào mồ côi.
CREATE TABLE voucher_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource     VARCHAR(60)  NOT NULL,
    voucher_id   BIGINT       NOT NULL,
    action       VARCHAR(20)  NOT NULL,
    from_status  VARCHAR(20),
    to_status    VARCHAR(20)  NOT NULL,
    step         VARCHAR(20),
    note         VARCHAR(500),
    actor_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    actor_name   VARCHAR(150),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_voucher_events_voucher ON voucher_events (resource, voucher_id, created_at);

-- ---------------------------------------------------------------- 2. Tệp đính kèm
--
-- Chứng từ gốc (hoá đơn, biên bản, quyết định) gắn vào phiếu hoặc thiết bị. Nội
-- dung nằm trong cơ sở dữ liệu như logo trường: một bản sao lưu là đủ, không có
-- thư mục tệp nào để quên sao lưu cùng.
CREATE TABLE attachments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource       VARCHAR(60)  NOT NULL,
    record_id      BIGINT       NOT NULL,
    file_name      VARCHAR(255) NOT NULL,
    content_type   VARCHAR(120) NOT NULL,
    size_bytes     BIGINT       NOT NULL,
    data           BYTEA        NOT NULL,
    note           VARCHAR(255),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE,
    created_by_id  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    updated_by_id  BIGINT REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX ix_attachments_record ON attachments (resource, record_id);

-- ---------------------------------------------------------------- 3. Nhật ký hoạt động
--
-- Mọi request làm thay đổi dữ liệu, và mọi lần xuất dữ liệu (HSMT 3.9.6). Ghi
-- ở tầng web cho MỌI endpoint một lần, thay vì nhớ gọi ở từng service.
CREATE TABLE activity_logs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    actor_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    actor_name   VARCHAR(150),
    method       VARCHAR(10)  NOT NULL,
    path         VARCHAR(500) NOT NULL,
    resource     VARCHAR(60),
    record_id    BIGINT,
    action       VARCHAR(40)  NOT NULL,
    status_code  INTEGER      NOT NULL,
    ip           VARCHAR(64)
);
CREATE INDEX ix_activity_logs_created ON activity_logs (created_at DESC);
CREATE INDEX ix_activity_logs_actor ON activity_logs (actor_id);
CREATE INDEX ix_activity_logs_resource ON activity_logs (resource, record_id);

-- ---------------------------------------------------------------- 4. Lịch sử thiết bị
--
-- Mỗi thay đổi trên một tài sản — ghi tăng, đổi phòng, đổi người giữ, đổi tình
-- trạng — là một dòng, kèm phiếu làm ra thay đổi đó. Đây là thứ trả lời "cái máy
-- này đã qua tay ai" mà không phải lục từng loại phiếu.
CREATE TABLE equipment_history (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id      BIGINT       NOT NULL REFERENCES equipment (id) ON DELETE CASCADE,
    action            VARCHAR(30)  NOT NULL,
    field             VARCHAR(40),
    from_value        VARCHAR(500),
    to_value          VARCHAR(500),
    voucher_resource  VARCHAR(60),
    voucher_id        BIGINT,
    voucher_code      VARCHAR(40),
    note              VARCHAR(500),
    actor_id          BIGINT REFERENCES users (id) ON DELETE SET NULL,
    actor_name        VARCHAR(150),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_equipment_history_equipment ON equipment_history (equipment_id, created_at);
CREATE INDEX ix_equipment_history_voucher ON equipment_history (voucher_resource, voucher_id);

-- ---------------------------------------------------------------- 5. Phiếu nhập vào vòng duyệt
--
-- Trước đây: nháp → xác nhận (một người, một bước). Giờ: nháp → trình → lãnh
-- đạo trường duyệt → ghi tăng. "Đã xác nhận" đổi tên thành "hoàn tất" để mọi
-- loại phiếu nói cùng một vốn từ trạng thái.
ALTER TABLE equipment_intakes
    ADD COLUMN approval_step    VARCHAR(20),
    ADD COLUMN submitted_at     TIMESTAMP WITH TIME ZONE,
    ADD COLUMN submitted_by_id  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    ADD COLUMN return_note      VARCHAR(500),
    ADD COLUMN reject_reason    VARCHAR(500);

ALTER TABLE equipment_intakes DROP CONSTRAINT ck_equipment_intakes_confirmed;
UPDATE equipment_intakes SET status = 'COMPLETED' WHERE status = 'CONFIRMED';
ALTER TABLE equipment_intakes ADD CONSTRAINT ck_equipment_intakes_completed CHECK (
    status <> 'COMPLETED' OR (code IS NOT NULL AND confirmed_at IS NOT NULL));

-- ---------------------------------------------------------------- 6. Quyền
INSERT INTO permissions (code, name, description, system_permission) VALUES
  ('activity_logs:read',   'Xem nhật ký hoạt động', 'Ai đã làm gì, lúc nào, trên dữ liệu nào', TRUE),
  ('activity_logs:export', 'Xuất nhật ký hoạt động', 'Xuất dữ liệu ra tệp (PDF, Excel hoặc CSV)', TRUE);

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r JOIN permissions p ON p.code IN ('activity_logs:read', 'activity_logs:export')
WHERE r.code = 'ADMIN';

-- Cán bộ thiết bị là người LẬP phiếu, nên không được DUYỆT phiếu: gộp hai việc
-- vào một người thì bước duyệt chỉ còn là hình thức. Quyền này được cấp ở 043
-- khi "xác nhận nhận hàng" còn là việc của người đứng nhận hàng.
DELETE FROM role_permissions
WHERE role_id = (SELECT id FROM roles WHERE code = 'SCHOOL_STAFF')
  AND permission_id = (SELECT id FROM permissions WHERE code = 'equipment_intakes:approve');

-- ---------------------------------------------------------------- 7. Phạm vi dữ liệu
--
-- 043 chỉ viết phạm vi cho bảng `schools`. Mọi bảng thuộc trường (thiết bị,
-- phiếu, cơ sở vật chất, cán bộ) chạy trên defaultScope = NONE, nên lãnh đạo
-- Sở, UBND và lãnh đạo trường mở ra đều thấy TRỐNG — và UBND không duyệt được
-- phiếu nào vì không đọc được phiếu nào.
--
-- UBND dùng khoá `user.managedSchoolIds`: tập các trường mà cơ quan của tài
-- khoản là cơ quan quản lý. Không cần cột cơ quan trên từng bảng nghiệp vụ.
WITH res(resource) AS (VALUES
    ('equipment'), ('equipment_intakes'), ('equipment_stock'),
    ('campuses'), ('buildings'), ('rooms'), ('staff')),
plan(role_code, action, name, description, scope) AS (VALUES
    ('SO_LEADER', 'read', 'Sở xem mọi trường', 'Sở GD&ĐT tổng hợp dữ liệu toàn ngành.', '{"all": []}'),
    ('SO_SPECIALIST', 'read', 'Sở xem mọi trường', 'Sở GD&ĐT tổng hợp dữ liệu toàn ngành.', '{"all": []}'),
    ('UBND_LEADER', 'read', 'UBND xem trường trên địa bàn',
     'Chỉ trường mà UBND này là cơ quan quản lý.',
     '{"field": "school.id", "op": "in", "value": {"ctx": "user.managedSchoolIds"}}'),
    ('UBND_SPECIALIST', 'read', 'UBND xem trường trên địa bàn',
     'Chỉ trường mà UBND này là cơ quan quản lý.',
     '{"field": "school.id", "op": "in", "value": {"ctx": "user.managedSchoolIds"}}'),
    ('SCHOOL_LEADER', 'read', 'Chỉ trường của mình', 'Chỉ dữ liệu của trường mà tài khoản được gán.',
     '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'),
    ('TEACHER', 'read', 'Chỉ trường của mình', 'Chỉ dữ liệu của trường mà tài khoản được gán.',
     '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'),
    ('SCHOOL_STAFF', 'delete', 'Chỉ trường của mình', 'Chỉ dữ liệu của trường mà tài khoản được gán.',
     '{"field": "school.id", "op": "eq", "value": {"ctx": "user.schoolId"}}'))
INSERT INTO row_level_policy (kind, role_id, resource, action, name, description, scope, created_at)
SELECT 'SCOPE', r.id, res.resource, plan.action, plan.name, plan.description, plan.scope::jsonb, now()
FROM plan
JOIN roles r ON r.code = plan.role_code
CROSS JOIN res
WHERE NOT (plan.role_code = 'SCHOOL_STAFF' AND res.resource NOT IN ('equipment', 'equipment_intakes'))
  AND NOT EXISTS (
      SELECT 1 FROM row_level_policy p
      WHERE p.role_id = r.id AND p.resource = res.resource AND p.action = plan.action);
